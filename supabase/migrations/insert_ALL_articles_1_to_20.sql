### El ecosistema más complejo que habitas

El ser humano alberga en su tracto gastrointestinal entre 10 y 100 billones de microorganismos pertenecientes a más de 1.000 especies distintas. Su peso combinado oscila entre 1 y 2 kilogramos. Su genoma colectivo —denominado metagenoma— contiene aproximadamente 150 veces más genes que el genoma humano propio.

Durante décadas, la medicina trató a estas bacterias como simples comensales, organismos que vivían en nosotros sin hacernos daño pero tampoco con ningún papel fisiológico relevante. Los últimos veinte años de investigación han demolido esta visión por completo.

El microbioma intestinal no es un pasajero pasivo. Es un órgano funcional activo que participa en la síntesis de vitaminas del grupo B y vitamina K, en la educación del sistema inmune desde los primeros días de vida, en la producción de metabolitos que regulan la motilidad intestinal y en la comunicación directa con el cerebro a través del nervio vago. Cuando este ecosistema pierde su equilibrio —cuando la proporción entre bacterias beneficiosas y oportunistas se invierte— las consecuencias pueden ir mucho más allá de un simple malestar estomacal.

A este desequilibrio lo llamamos disbiosis.

---

### ¿Qué es exactamente la disbiosis y qué no es?

La disbiosis no es una enfermedad con una definición clínica única y universalmente aceptada. Es un término funcional que describe tres tipos de alteraciones que pueden ocurrir de forma simultánea o aislada en el ecosistema microbiano:

1. **Pérdida de diversidad:** Una microbiota saludable tiene una gran variedad de especies. La pérdida de diversidad —aunque aumenten las bacterias buenas en términos absolutos— reduce la resiliencia del sistema ante agresiones externas.
2. **Cambio en la proporción de grupos dominantes:** El ratio entre los dos filos bacterianos más abundantes del intestino humano —Firmicutes y Bacteroidetes— se altera. Algunos estudios asocian un aumento de Firmicutes con obesidad y resistencia a la insulina.
3. **Expansión de microorganismos oportunistas:** Bacterias como *Escherichia coli* enteropatogénica, *Clostridium difficile* o ciertas proteobacterias proliferan en detrimento de géneros protectores como *Lactobacillus*, *Bifidobacterium* y los productores de butirato.

Es importante señalar que la ciencia aún no ha establecido un perfil único de "microbiota sana". La composición microbiana varía significativamente entre individuos, culturas, geografías y etapas de vida. Lo que sí es consistente en la literatura es la asociación entre menor diversidad, menor presencia de bacterias productoras de butirato y mayor inflamación sistémica.

