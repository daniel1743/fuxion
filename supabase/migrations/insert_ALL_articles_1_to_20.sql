### Preguntas frecuentes

**¿Cómo se diagnostica la IPE?**
La prueba de referencia es la determinación de **elastasa pancreática en heces** (PE-1). Valores superiores a 200 µg/g de heces se consideran normales; entre 100-200 µg/g indican IPE moderada; por debajo de 100 µg/g, IPE grave. Es una prueba accesible, no invasiva y ampliamente disponible. Complementariamente, la prueba de aliento con triglicéridos marcados (ⁱ³C-MTG) evalúa la digestión de grasas de forma funcional.

**¿Qué es el tratamiento TREP y cómo se toma?**
La Terapia de Reemplazo Enzimático Pancreático (TREP) consiste en cápsulas con enzimas pancreáticas de origen porcino con recubrimiento entérico. Se toma al inicio de cada comida principal (y a la mitad si la comida es larga). La dosis se ajusta individualmente según el contenido en grasas de la dieta y la respuesta sintomática. Es un tratamiento de por vida en casos de IPE crónica.

**¿Afecta la edad a la capacidad digestiva?**
Sí, de forma gradual. Con la edad disminuye la producción de ácido gástrico (hipoclorhidria), lo que reduce la estimulación de secretina y CCK, y en consecuencia la secreción pancreática. También disminuye la expresión de enzimas del borde en cepillo (especialmente lactasa). Esto explica por qué muchas personas mayores desarrollan intolerancia a la lactosa y menor eficiencia digestiva en general, sin tener ninguna enfermedad pancreática diagnosticada.

**¿La dispepsia (digestión lenta y pesada) se debe a insuficiencia enzimática?**
La dispepsia funcional y la IPE pueden compartir algunos síntomas (sensación de plenitud, distensión), pero son condiciones diferentes. La dispepsia funcional tiene como mecanismo principal la hipersensibilidad gástrica y el vaciado gástrico lento, no la insuficiencia enzimática pancreática. Los suplementos enzimáticos pueden ayudar en casos de dispepsia asociada a comidas muy ricas en grasas, pero no son un tratamiento universal para la dispepsia.

**¿Es posible apoyar la digestión enzimática con la dieta?**
Algunos alimentos contienen enzimas digestivas naturales que pueden complementar (aunque no reemplazar) las enzimas endógenas: la papaya contiene papaína (proteolítica), la piña contiene bromelina (proteolítica), y el mango y la papaya contienen amilasas naturales. Sin embargo, estas enzimas vegetales tienen una actividad mucho menor que las pancreáticas y pueden ser degradadas por el pH gástrico antes de llegar al intestino delgado.

