### Desmitificación Científica

**Mito 1:** "El SII es una enfermedad psicológica, está en la cabeza del paciente."
**Realidad:** El SII tiene mecanismos biológicos documentados: hipersensibilidad visceral con cambios en la densidad de receptores nerviosos, permeabilidad intestinal aumentada medible con biomarcadores, alteraciones objetivas del microbioma y cambios en la expresión de serotonina intestinal. Que el estrés lo agrave no significa que sea "solo mental": el estrés tiene efectos fisiológicos reales y medibles en el intestino a través del eje intestino-cerebro.

**Mito 2:** "Si tengo SII, debo evitar toda la fibra."
**Realidad:** La fibra insoluble (salvado de trigo) puede empeorar el SII-D y la distensión, pero la fibra soluble (psyllium, semillas de chía en pequeñas cantidades) tiene evidencia moderada de beneficio en el SII-E y en la regularización del tránsito. La recomendación no es eliminar la fibra, sino elegir el tipo correcto y aumentarla de forma gradual.

**Mito 3:** "El SII es una condición de por vida que nunca mejora."
**Realidad:** El SII tiene una historia natural variable. Algunos estudios de seguimiento a 5-10 años muestran que entre el 20-30% de los pacientes entran en remisión sostenida. El manejo multimodal —dietético, psicoterapéutico y cuando está indicado farmacológico— mejora significativamente la calidad de vida y puede reducir la frecuencia e intensidad de los episodios a niveles manejables o mínimos.

