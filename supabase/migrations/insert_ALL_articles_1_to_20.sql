### Desmitificación Científica

**Mito 1:** "El hígado graso solo afecta a personas obesas o con sobrepeso visible."
**Realidad:** Existe un fenotipo clínico documentado llamado "HGNA magro" o "lean NAFLD", en el que personas con IMC normal (< 25) desarrollan infiltración grasa hepática. Se estima que representa entre el 10-20% de todos los casos de HGNA. Los factores principales en este grupo son la adiposidad visceral (grasa alrededor de los órganos internos sin exceso de grasa subcutánea visible), la resistencia a la insulina periférica y la variante genética PNPLA3 I148M.

**Mito 2:** "El hígado graso se detecta fácilmente en los análisis de sangre."
**Realidad:** Los parámetros más usados para detectar el daño hepático —ALT y AST— pueden ser completamente normales en estadios de esteatosis simple e incluso de fibrosis inicial. La ecografía abdominal detecta la esteatosis cuando supera el 20-30% de infiltración; para etapas más tempranas o para determinar el grado de fibrosis, se requiere elastografía (Fibroscan) o biopsia hepática.

**Mito 3:** "El hígado graso es irreversible."
**Realidad:** La esteatosis simple y la EHNA leve-moderada son potencialmente reversibles. Múltiples ensayos clínicos han demostrado resolución histológica completa de la esteatohepatitis en pacientes que lograron una pérdida del 10% del peso corporal y mantuvieron cambios en el estilo de vida. La cirrosis, sin embargo, tiene una capacidad de reversión muy limitada y requiere seguimiento especializado indefinido.

