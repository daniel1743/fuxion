### Fisiopatología: los tres tipos de gas y lo que cada uno revela

El tipo de bacteria que coloniza el intestino delgado determina el perfil de gases producidos y, por tanto, los síntomas dominantes. Esta distinción es clínicamente relevante porque orienta tanto el diagnóstico como el abordaje.

| Tipo de Gas | Microorganismo Asociado | Síntoma Predominante | Patrón Típico |
| :--- | :--- | :--- | :--- |
| **Hidrógeno (H₂)** | Bacterias gramnegativas anaerobias | Diarrea explosiva, dolor cólico agudo | Distensión postprandial temprana |
| **Metano (CH₄)** | Arqueas metanogénicas (*Methanobrevibacter smithii*) | Estreñimiento obstinado, heces de tránsito lento | Saciedad precoz, sensación de bloqueo |
| **Sulfuro de Hidrógeno (H₂S)** | Bacterias reductoras de sulfato | Heces con olor sulfuroso, fatiga sistémica intensa | Síntomas extradigestivos prominentes |
| **Mixto (H₂ + CH₄)** | Coexistencia de ambas poblaciones | Alternancia diarrea-estreñimiento | Cuadro típicamente confundido con SII |

El metano merece una mención especial: las arqueas que lo producen no son bacterias en sentido estricto —pertenecen a un dominio separado de la vida— y su presencia enlentece el tránsito intestinal porque el gas metano tiene un efecto inhibidor directo sobre las contracciones del músculo liso intestinal.

