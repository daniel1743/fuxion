### Sensibilidad al Gluten No Celíaca: lo que la ciencia sabe (y lo que aún no)

La SGNC es, en muchos sentidos, el territorio más difícil de este espectro para el médico y el paciente por igual. Fue reconocida formalmente como entidad clínica diferenciada solo a partir de los Consensos de Expertos de Oslo (2012) y Salerno (2015). Antes de eso, muchos de estos pacientes recibían diagnósticos de exclusión poco satisfactorios.

Lo que la ciencia ha establecido hasta ahora:
- La SGNC produce síntomas digestivos (distensión, dolor abdominal, diarrea o estreñimiento) y extradigestivos (niebla mental, fatiga, cefalea, erupciones cutáneas) tras la ingesta de trigo, cebada o centeno.
- No hay atrofia de vellosidades (Marsh 0 o 1 máximo).
- No hay autoanticuerpos específicos (anti-tTG negativo, anti-endomisio negativo).
- Los genes HLA-DQ2/DQ8 están presentes en el 50% de los casos (versus 95% en EC), lo que sugiere una predisposición parcial.

#### ¿Es realmente el gluten el culpable en la SGNC?

Este es uno de los debates más activos en la gastroenterología de la última década. Investigaciones del Dr. Peter Gibson en Australia —el mismo científico que popularizó la dieta FODMAP— han puesto en duda que el gluten sea el verdadero desencadenante en la SGNC.

Sus ensayos controlados con doble ciego han mostrado que los síntomas de muchos pacientes con SGNC no empeoran de forma reproducible al exponerse específicamente al gluten, sino que pueden estar mediados por los **fructanos** del trigo: un tipo de carbohidrato fermentable (perteneciente al grupo de los FODMAPs) que también se encuentra en el ajo, la cebolla y otros vegetales. Esto explicaría por qué muchos pacientes con "SGNC" mejoran al eliminar el trigo, pero también al eliminar otros alimentos con fructanos, sin que el gluten en sí sea el agente activo.

Esta hipótesis no invalida la SGNC como entidad clínica, pero sí complejiza el mensaje popular de que "el gluten es tóxico para todos".

