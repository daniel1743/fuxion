### Estrategia para aumentar el consumo: por qué el "de golpe" no funciona

El error más común al intentar mejorar el consumo de fibra es aumentarlo bruscamente. El resultado predecible es una semana de distensión abdominal, gases y malestar que lleva al abandono.

El motivo es microbiológico: la microbiota necesita tiempo para adaptarse al nuevo sustrato. Cuando aparece más fibra de la que las bacterias están acostumbradas a procesar, la fermentación se acelera en exceso, produciendo volúmenes de gas que el intestino no puede manejar cómodamente.

La estrategia basada en evidencia es:
1. **Incremento gradual:** Aumentar 3-5g por semana durante 4-6 semanas hasta alcanzar el objetivo.
2. **Hidratación adecuada:** La fibra, especialmente la insoluble, requiere agua para funcionar correctamente. Sin hidratación suficiente, puede empeorar el estreñimiento.
3. **Diversificación progresiva:** Introducir nuevas fuentes de fibra una a una para identificar cuáles el organismo tolera mejor en cada momento.
4. **Cocinado adecuado:** Las legumbres remojadas y bien cocidas son mejor toleradas que las enlatadas y, estas, mejor que crudas.

