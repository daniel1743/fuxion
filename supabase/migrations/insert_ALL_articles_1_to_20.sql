### Un huésped que llegó para quedarse

Imagina un organismo capaz de vivir en el lugar más hostil del sistema digestivo humano: un ambiente bañado por ácido clorhídrico concentrado, con un pH que oscila entre 1 y 3. Durante décadas, la comunidad científica consideró imposible que alguna bacteria pudiera colonizar el estómago humano. Sin embargo, en 1982, los doctores Barry Marshall y Robin Warren demostraron lo contrario, cambiando para siempre nuestra comprensión de la gastritis y la úlcera péptica. Hoy sabemos que *Helicobacter pylori* no solo existe en ese entorno, sino que lo ha habitado durante al menos 100.000 años de coevolución con nuestra especie.

### ¿Qué es exactamente Helicobacter pylori?

*Helicobacter pylori* es una bacteria espiralada, flagelada y microaerófila, lo que significa que requiere concentraciones reducidas de oxígeno para crecer. Su forma helicoidal y sus flagelos le permiten perforar la capa de moco que recubre el estómago y alcanzar la superficie del epitelio gástrico, donde el pH es ligeramente más neutro. Una vez allí, se adhiere firmemente a las células mediante proteínas de adhesión específicas, como BabA y SabA, y comienza a establecer una colonia que puede persistir durante toda la vida del huésped si no se interviene.

