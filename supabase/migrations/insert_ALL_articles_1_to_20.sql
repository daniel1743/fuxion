### Antes de que el nutriente llegue a la sangre: el proceso que nadie ve

Cuando piensas en nutrición, probablemente piensas en qué comer. Pero existe un proceso previo, invisible y extraordinariamente sofisticado, sin el cual los alimentos más nutritivos del mundo pasarían por el intestino sin dejar rastro: la digestión enzimática.

No basta con ingerir proteínas, grasas y carbohidratos. El intestino delgado —el órgano que absorbe los nutrientes hacia el torrente sanguíneo— no puede absorber una proteína entera ni un triglicérido en su forma original. Para que la absorción sea posible, cada macromolécula debe ser descompuesta en sus unidades más pequeñas: los carbohidratos en monosacáridos, las proteínas en aminoácidos y péptidos cortos, y las grasas en ácidos grasos libres y monoglicéridos.

Esta operación de deconstrucción molecular es responsabilidad de un sistema enzimático que involucra tres actores principales: la **saliva** (primera línea), el **páncreas exocrino** (actor central y más potente) y la **bilis hepática** (emulsionante esencial para las grasas). El intestino delgado aporta además enzimas en el borde de sus propias células (las **enzimas del borde en cepillo**).

Comprender cómo funciona este sistema —y qué ocurre cuando falla— es comprender por qué dos personas que comen exactamente lo mismo pueden tener estados nutricionales radicalmente diferentes.

---

### El páncreas: el órgano con dos identidades

El páncreas es un órgano de aproximadamente 15 centímetros de longitud, ubicado en el retroperitoneo, entre el duodeno y el bazo. Tiene dos funciones completamente distintas que coexisten en el mismo tejido:

**Función endocrina** (~2% del tejido): Los islotes de Langerhans producen hormones que se vierten directamente al torrente sanguíneo: insulina (regula la glucosa), glucagón (eleva la glucosa) y somatostatina (moduladora).

**Función exocrina** (~98% del tejido): Las células acinares producen y secretan enzimas digestivas hacia el duodeno a través del conducto pancreático principal (conducto de Wirsung). Este es el componente que nos ocupa.

El páncreas exocrino secreta entre **1,5 y 3 litros de jugo pancreático diario**, con un pH alcalino de 7,6–8,2 (gracias al bicarbonato que neutraliza el ácido gástrico al llegar al duodeno). Esta alcalinización es esencial: las enzimas pancreáticas son inactivas o degradadas en medio ácido y solo funcionan correctamente en pH neutro-alcalino.

---

### El mecanismo de activación: del estímulo al duodeno

La secreción pancreática no es continua; se activa en respuesta a la presencia de alimentos mediante dos hormonas intestinales claves:

**Secretina:** Producida por las células S del duodeno cuando detectan el bolo ácido procedente del estómago. Estimula la secreción de bicarbonato y agua para neutralizar el pH duodenal.

**Colecistoquinina (CCK):** Producida por las células I del duodeno en respuesta a la presencia de grasas y proteínas. Estimula la secreción de enzimas pancreáticas y contrae la vesícula biliar para liberar bilis al duodeno.

Este sistema de señalización garantiza que las enzimas se secreten solo cuando hay sustrato (alimento) al que actuar, evitando la autodigestión del páncreas. Un mecanismo de seguridad adicional es que las proteasas pancreáticas (tripsina, quimotripsina, elastasa) se secretan en forma de **zimógenos inactivos** (tripsinógeno, quimotripsinógeno) que solo se activan en el lumen duodenal por acción de la **enteroquinasa** del borde en cepillo intestinal.

