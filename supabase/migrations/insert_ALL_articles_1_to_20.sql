### Preguntas frecuentes

**¿Existe algún medicamento aprobado para el HGNA/MASLD?**
Durante años no existía ninguno. En 2024, la FDA aprobó el primer medicamento específico para la MASH con fibrosis: el resmetirom (Rezdiffra), un agonista del receptor tiroideo beta que reduce la lipogénesis hepática. Sin embargo, la modificación del estilo de vida sigue siendo la base del tratamiento en todos los estadios.

**¿Qué pruebas de imagen son más útiles para el seguimiento?**
La ecografía abdominal es la más accesible pero menos sensible para estadios tempranos. La elastografía hepática (Fibroscan) evalúa el grado de fibrosis de forma no invasiva y con mayor precisión. La resonancia magnética con espectroscopia es el patrón oro para cuantificar la grasa hepática, pero es cara y de uso principalmente en investigación.

**¿El HGNA puede evolucionar a cáncer de hígado?**
Sí, aunque en una minoría de casos. La cirrosis por EHNA/MASH es un factor de riesgo para el carcinoma hepatocelular. El riesgo es menor que en la cirrosis por hepatitis viral, pero es un motivo adicional para tratar la enfermedad de forma precoz y no permitir su progresión silenciosa.

**¿Los suplementos como la silimarina (cardo mariano) o la vitamina E ayudan?**
La vitamina E (800 UI/día) mostró reducir la inflamación hepática en pacientes con EHNA en el ensayo clínico PIVENS (publicado en NEJM, 2010), pero solo en adultos sin diabetes y sin cirrosis. La silimarina tiene evidencia limitada y heterogénea. Ninguno de los dos sustituye las intervenciones de estilo de vida y deben usarse bajo supervisión médica.

**¿Hay una dieta específica mejor que otras para el HGNA?**
La dieta mediterránea tiene el mayor respaldo científico acumulado para el HGNA específicamente. Otras aproximaciones con evidencia emergente incluyen la dieta baja en carbohidratos y la restricción de fructosa libre. Las dietas muy bajas en calorías con supervisión médica (800-1.200 kcal/día) producen reducciones rápidas de grasa hepática pero deben hacerse con control médico y nutricional estricto para evitar el efecto rebote y el agravamiento inflamatorio.

