### Desmitificación Científica

**Mito 1:** "El reflujo siempre se debe a que el estómago produce demasiado ácido."
**Realidad:** La hipoclorhidria —niveles insuficientes de ácido— puede producir síntomas idénticos al exceso de ácido. La monitorización del pH esofágico durante 24 horas es la única forma de distinguir entre ambos con certeza. Tratar la hipoclorhidria con antiácidos puede agravar el cuadro.

**Mito 2:** "Tomar leche calma el ardor."
**Realidad:** La leche produce un efecto neutralizante inmediato gracias a sus proteínas y calcio. Sin embargo, su alto contenido en grasa relaja el EEI y estimula la producción secundaria de ácido. El alivio inicial suele ir seguido de un empeoramiento de los síntomas 1-2 horas después.

**Mito 3:** "Los inhibidores de bomba de protones son perfectamente seguros para tomarse de por vida sin revisión."
**Realidad:** Los IBP son medicamentos seguros para usos concretos y durations definidas. La evidencia acumulada desde 2010 señala riesgos asociados al uso crónico —especialmente en malabsorción de micronutrientes y disbiosis— que requieren seguimiento médico periódico y reevaluación de la indicación.

