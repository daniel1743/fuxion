### El gluten: de ingrediente a controversia global

Pocas palabras en el vocabulario de la salud contemporánea han generado tanto debate como "gluten". En menos de dos décadas, ha pasado de ser un componente anónimo del pan a convertirse en el protagonista de movimientos dietéticos masivos, libros de autoayuda y pasillos enteros de supermercados con etiquetas de "libre de gluten". Al mismo tiempo, la ciencia médica ha identificado que, para una fracción específica de la población, el gluten no es simplemente una moda alimentaria a evitar: es un desencadenante bioquímico que activa mecanismos de daño orgánico con consecuencias graves y acumulativas.

Distinguir entre estas dos realidades —la cultural y la clínica— es uno de los mayores desafíos de la gastroenterología contemporánea. Y hacerlo con rigor no es solo un ejercicio académico: tiene implicaciones directas sobre el diagnóstico, el tratamiento y la calidad de vida de millones de personas.

El espectro de los trastornos relacionados con el gluten incluye al menos tres entidades bien diferenciadas: la Enfermedad Celíaca (autoinmune), la Alergia al Trigo (mediada por IgE) y la Sensibilidad al Gluten No Celíaca (de mecanismo aún en estudio). Cada una tiene un perfil inmunológico distinto, consecuencias orgánicas diferentes y abordajes clínicos que no son intercambiables.

