### El nutriente que la digestión no puede digerir

La fibra dietética tiene una paradoja en su esencia: es un nutriente que el organismo humano no puede procesar directamente, y sin embargo es indispensable para la salud. No aporta calorías absorbibles en el intestino delgado, no se convierte en glucosa, no libera aminoácidos. Sin embargo, su ausencia sostenida de la dieta se asocia de forma consistente en la literatura científica con mayor riesgo de enfermedad cardiovascular, diabetes tipo 2, cáncer colorrectal, estreñimiento crónico, disbiosis y síndrome metabólico.

En los países occidentales, el consumo promedio de fibra ronda los 15 gramos diarios. Las recomendaciones de organismos como la OMS, la Asociación Americana del Corazón y la EFSA establecen entre 25 y 38 gramos diarios como objetivo para adultos. La brecha entre lo que comemos y lo que necesitamos representa uno de los déficits nutricionales más extendidos pero menos discutidos de la alimentación contemporánea.

Entender qué es la fibra, por qué existe esa distinción entre soluble e insoluble y qué hace cada una en el tracto digestivo es el primer paso para construir un patrón dietético que apoye genuinamente la salud intestinal.

