### La hinchazón que no cede: cuando el problema está en el lugar equivocado

Existe una queja digestiva que los especialistas escuchan con alta frecuencia en sus consultas: el paciente describe una hinchazón abdominal tan intensa que aparece a los pocos minutos de comer —incluso cuando la comida ha sido pequeña y "saludable"— y que ningún antiácido, probiótico ni dieta de exclusión ha logrado resolver de manera definitiva.

Durante años, ese cuadro fue encasillado bajo el paraguas vago del "colon irritable". Sin embargo, la gastroenterología moderna ha identificado que, en un porcentaje significativo de esos casos, la raíz del problema no es una sensibilidad anormal al estrés ni una respuesta exagerada del sistema nervioso: es una cuestión de dirección y de geografía microbiana.

El intestino humano no es un tubo uniforme. Es un sistema de cámaras con funciones radicalmente distintas. El intestino delgado —que mide entre 6 y 7 metros en el adulto— está diseñado casi exclusivamente para la absorción. El colon, en cambio, es el gran fermentador del organismo, habitado por billones de bacterias que procesan lo que el intestino delgado no pudo digerir. El SIBO ocurre cuando esta separación funcional se rompe: las bacterias del colon suben río arriba, instalan su actividad fermentativa en una zona donde no deberían estar y se apoderan del trabajo que el cuerpo necesitaba para absorber sus nutrientes.

El problema, por tanto, no es que las bacterias sean "malas". El problema es que están en el lugar equivocado.

