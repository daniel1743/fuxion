### El papel del eje intestino-hígado en el HGNA

Uno de los descubrimientos más importantes de la última década es que el HGNA no es solo una consecuencia de lo que comemos: también es una consecuencia del estado de nuestro microbioma intestinal.

Las personas con HGNA muestran consistentemente patrones de disbiosis con:
- **Menor abundancia** de *Faecalibacterium prausnitzii*, *Akkermansia muciniphila* y productores de butirato.
- **Mayor abundancia** de *Escherichia coli* y otras proteobacterias que producen etanol endógeno y lipopolisacáridos (LPS).

El LPS producido por las bacterias gramnegativas atraviesa una barrera intestinal permeabilizada, entra al torrente sanguíneo y viaja directamente al hígado. Allí activa los receptores TLR4 de las células de Kupffer (los macrófagos residentes del hígado), que disparan una respuesta inflamatoria que contribuye a la progresión de la esteatosis hacia la esteatohepatitis.

Este mecanismo explica por qué la salud intestinal es relevante para la salud hepática, y por qué intervenciones que mejoran la microbiota (dieta rica en fibra, fermentados, ejercicio) tienen efectos medibles sobre los marcadores hepáticos.

