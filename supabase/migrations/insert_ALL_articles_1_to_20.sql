### Preguntas frecuentes

**¿Cómo puedo saber si tengo hipoclorhidria o exceso de ácido?**
Los síntomas son clínicamente indistinguibles. La prueba estándar es la monitorización ambulatoria del pH esofágico durante 24-48 horas (pH-metría), que mide directamente cuánto tiempo el esófago está expuesto a un pH ácido o alcalino. El médico puede también solicitar una manometría esofágica de alta resolución para evaluar la función del EEI.

**¿La infección por *Helicobacter pylori* causa reflujo?**
La relación es compleja. *H. pylori* puede causar tanto gastritis hipersecretora (más ácido) como atrofia gástrica con hipoclorhidria (menos ácido), dependiendo de la cepa y la región del estómago afectada. La erradicación de *H. pylori* puede, en algunos casos, mejorar el ERGE y, en otros, desenmascarlo al restaurar la producción de ácido.

**¿Existe relación entre el ERGE y el asma?**
Sí. El reflujo puede desencadenar o agravar el asma bronquial mediante dos mecanismos: microaspiraciones de contenido gástrico hacia las vías respiratorias, y un reflejo vagal que contrae los bronquios en respuesta a la acidez esofágica. Se estima que hasta el 30-40% de los pacientes asmáticos tienen ERGE coexistente.

**¿El estrés crónico agrava el reflujo?**
Sí. El estrés activa el sistema nervioso autónomo y puede reducir el tono del EEI, alterar la motilidad esofágica y modificar la percepción del dolor, haciendo que síntomas leves sean percibidos como severos. Además, el estrés crónico favorece conductas que agravan el reflujo (tabaco, alcohol, comer rápido, descanso insuficiente).

**¿Cenar muy poco podría ayudar al reflujo?**
Sí. Reducir el volumen de la última comida del día y dejar al menos 3 horas entre la cena y el momento de acostarse son medidas con respaldo clínico para reducir la distensión gástrica nocturna y la frecuencia de episodios de reflujo durante el sueño.

