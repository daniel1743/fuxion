### El estrés como perturbador del eje: una relación de doble sentido

El eje intestino-cerebro no solo transmite información del intestino al cerebro. También transmite en dirección opuesta, y el estrés crónico es el ejemplo más documentado de cómo el cerebro deteriora el intestino.

Cuando el sistema nervioso autónomo activa la respuesta de "lucha o huida" ante un estresor, sucede una cascada de cambios fisiológicos en el intestino:

| Efecto del Estrés en el Intestino | Mecanismo | Consecuencia |
| :--- | :--- | :--- |
| Reducción del flujo sanguíneo intestinal | Vasoconstricción esplácnica | Menor oxigenación del epitelio y la microbiota |
| Inhibición del peristaltismo | Supresión vagal durante respuesta simpática | Enlentecimiento del tránsito o diarrea por estrés agudo |
| Aumento de la permeabilidad intestinal | El cortisol debilita las uniones estrechas | Mayor paso de LPS al torrente sanguíneo |
| Reducción de IgA secretora | Supresión inmune local | Mayor vulnerabilidad a infecciones entéricas |
| Alteración de la microbiota | Cambios en el pH, flujo biliar y motilidad | Disbiosis secundaria al estrés |

Esta cascada explica por qué condiciones como el Síndrome del Intestino Irritable empeoran marcadamente durante períodos de estrés, por qué las personas con ansiedad reportan problemas digestivos crónicos, y por qué las intervenciones sobre el estrés (mindfulness, ejercicio moderado) tienen efectos documentados sobre la microbiota y la motilidad intestinal.

