Depende de la causa subyacente. Si el desequilibrio se debe a un factor transitorio (como una infección intestinal o el uso temporal de un medicamento inhibidor de DAO), es posible que se resuelva al eliminar ese factor. Si existe una predisposición genética o una condición crónica (como una enfermedad inflamatoria intestinal), el manejo suele ser a largo plazo.

