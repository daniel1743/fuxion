### ¿Cuándo consultar a un profesional de la salud?

Busque evaluación médica con un gastroenterólogo si presenta:

- Sangre visible en las heces o deposiciones negras, brillantes y malolientes (melenas).
- Pérdida de peso involuntaria significativa (más del 5% en 3 meses) sin causa aparente.
- Dolor abdominal nocturno que le despierta del sueño.
- Anemia ferropénica refractaria al tratamiento con hierro oral.
- Cambios persistentes en el calibre de las heces o en los hábitos intestinales de más de 4 semanas de duración.
- Fiebre asociada a síntomas digestivos.
- Antecedentes familiares de enfermedad inflamatoria intestinal o cáncer colorrectal con síntomas nuevos.

