### El rol de la bilis: el emulsionante que las grasas necesitan

El páncreas solo produce la lipasa. Pero la lipasa por sí sola tiene un problema: los triglicéridos son hidrofóbicos (no se mezclan con el agua del ambiente intestinal) y forman grandes glóbulos que la lipasa no puede atacar eficientemente porque solo puede actuar en la superficie del glóbulo.

Aquí entra la **bilis**, producida por el hígado y almacenada en la vesícula biliar. La bilis contiene sales biliares que actúan como detergentes biológicos: rodean los glóbulos de grasa, los fragmentan en gotículas microscópicas (emulsificación) y exponiendo una superficie de contacto enormemente mayor para que la lipasa pancreática pueda actuar.

Sin bilis, la digestión de las grasas es gravemente deficiente aunque el páncreas funcione perfectamente. Por eso, las enfermedades que afectan al hígado, los conductos biliares o la vesícula biliar (colestasis, cálculos biliares, cirrosis) también producen síntomas de malabsorción de grasas.

---

### El viaje de cada macronutriente

#### Los carbohidratos: de almidón a glucosa

1. **Boca:** La amilasa salival comienza a fragmentar los almidones en maltosa y dextrinas (actúa 30-60 segundos antes de que el bolo llegue al estómago).
2. **Estómago:** La amilasa salival se inactiva con el ácido gástrico; no hay digestión significativa de carbohidratos.
3. **Duodeno/Yeyuno:** La amilasa pancreática completa la fragmentación de almidones. Las enzimas del borde en cepillo (maltasa, sacarasa, lactasa) convierten los disacáridos en monosacáridos (glucosa, fructosa, galactosa).
4. **Absorción:** Los monosacáridos son absorbidos por transportadores específicos (SGLT1 para glucosa y galactosa, GLUT5 para fructosa) en el yeyuno.

#### Las proteínas: de cadenas largas a aminoácidos

1. **Estómago:** La pepsina (activada por el HCl) realiza una digestión proteica preliminar, rompiendo proteínas en polipéptidos más cortos.
2. **Duodeno:** La tripsina y la quimotripsina fraccionan los polipéptidos en fragmentos más pequeños. Las carboxipeptidasas liberan aminoácidos individuales desde los extremos.
3. **Borde en cepillo:** Las peptidasas intestinales completan la digestión de dipéptidos y tripéptidos en aminoácidos individuales.
4. **Absorción:** Los aminoácidos y dipéptidos pequeños son absorbidos por transportadores específicos (sistema PepT1) en el yeyuno.

#### Las grasas: de triglicéridos a ácidos grasos

1. **Estómago:** La lipasa gástrica realiza una digestión lipídica inicial limitada (~10-30%).
2. **Duodeno:** La bilis emulsifica los glóbulos de grasa. La lipasa pancreática (asistida por colipasa) hidroliza los triglicéridos en ácidos grasos libres y monoglicéridos.
3. **Formación de micelas:** Los ácidos grasos y monoglicéridos se incorporan a micelas mixtas (junto a sales biliares y colesterol) que transportan las moléculas lipídicas hasta la superficie del enterocito.
4. **Absorción:** Los lípidos difunden al interior del enterocito, se reensamblan en triglicéridos, se empacan en quilomicrones y se secretan al sistema linfático (no directamente a la sangre portal, a diferencia de carbohidratos y proteínas).

---

### Insuficiencia Pancreática Exocrina (IPE): cuando el sistema falla

La IPE es la incapacidad del páncreas de producir y/o secretar suficiente cantidad de enzimas digestivas para mantener una digestión y absorción normales. Se manifiesta clínicamente cuando la capacidad secretora ha caído por debajo del **10% de lo normal** —el páncreas tiene una enorme reserva funcional.

| Causa de IPE | Mecanismo | Población Más Afectada |
| :--- | :--- | :--- |
| **Pancreatitis crónica** | Destrucción fibrótica del tejido acinar | Adultos con abuso de alcohol o hipercalcemia crónica |
| **Fibrosis quística** | Mutación CFTR → obstrucción de conductos pancreáticos | Niños y adultos jóvenes con diagnóstico genético |
| **Cirugía pancreática** | Resección de tejido acinar funcional | Postoperatorio de pancreatectomías o Whipple |
| **Diabetes mellitus tipo 1 y 2** | Inflamación crónica de los islotes que afecta el tejido acinar adyacente | Adultos con diabetes de larga evolución |
| **Enfermedad celíaca** | Atrofia vellosa que reduce la producción de secretina y CCK (secundaria) | Celíacos no tratados o con mal control |
| **Edad avanzada** | Reducción progresiva de la reserva funcional exocrina | Mayores de 70 años |

**Síntomas clave de la IPE:**
- Esteatorrea: heces pálidas, grasientas, malolientes, difíciles de limpiar del inodoro.
- Pérdida de peso mantenida a pesar de ingesta calórica normal.
- Distensión abdominal y flatulencia persistente.
- Déficit de vitaminas liposolubles (A, D, E, K): ceguera nocturna, osteoporosis, neuropatía, coagulopatía.
- Déficit de vitamina B12 (por insuficiente proteasa para liberar la B12 de sus proteínas transportadoras en el alimento).

---

### Desmitificación Científica

**Mito 1:** "Los suplementos enzimáticos de venta libre pueden tratar la IPE."
**Realidad:** Los suplementos enzimáticos de farmacia contienen concentraciones de lipasa muy inferiores a las formulaciones de prescripción. La Terapia de Reemplazo Enzimático Pancreático (TREP) farmacéutica (Creon, Zenpep, Pancreaze) contiene formulaciones con recubrimiento entérico que protegen las enzimas del ácido gástrico y las libera en el duodeno. Sin recubrimiento entérico, la mayoría de las enzimas orales se degradan antes de llegar al intestino donde se necesitan.

**Mito 2:** "Masticar rápido no afecta a la digestión siempre que el páncreas funcione."
**Realidad:** La masticación adecuada tiene tres efectos relevantes: fragmenta mecánicamente los alimentos aumentando la superficie de contacto con las enzimas, mezcla los alimentos con amilasa salival para la predigestión de almidones, y activa reflexivamente (fase cefálica) la secreción de jugos gástrico y pancreático. Tragar sin masticar bien no solo reduce la eficiencia digestiva sino que sobrecarga el sistema enzimático del intestino delgado.

**Mito 3:** "Si no tengo síntomas digestivos, mi digestión enzimática es perfecta."
**Realidad:** La IPE solo produce síntomas clínicos cuando la capacidad secretora cae por debajo del 10%. Entre el 10% y el 100% de capacidad normal existe una zona de "insuficiencia subclínica" donde la digestión es subóptima pero sin síntomas manifiestos. Factores como el envejecimiento, el estrés crónico (que inhibe la señalización vagal de la secreción pancreática) y la hipoclorhidria (que reduce la activación de secretina por falta de acidez duodenal) pueden reducir la eficiencia digestiva sin producir síntomas claros.

---

### ¿Cuándo consultar a un profesional de la salud?

Busque evaluación médica urgente con un gastroenterólogo ante:

- Heces pálidas, brillantes, grasientas y malolientes de forma persistente (esteatorrea).
- Dolor severo en el epigastrio o en el hipocondrio izquierdo que se irradia hacia la espalda (posible pancreatitis).
- Pérdida de peso significativa (más del 5% en 3 meses) manteniendo la misma ingesta calórica.
- Aparición de ictericia (coloración amarilla en piel y ojos) con síntomas digestivos.
- Diagnóstico previo de pancreatitis aguda o crónica con nuevos síntomas de malabsorción.
- Análisis de sangre que muestran déficit de vitaminas liposolubles (D, K, A, E) sin causa aparente.

