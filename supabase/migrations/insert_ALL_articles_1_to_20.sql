### Lo que la evidencia respalda para el manejo del HGNA

> **Nota importante:** Las siguientes estrategias tienen respaldo en literatura revisada por pares pero deben implementarse bajo supervisión médica, especialmente en presencia de fibrosis avanzada, diabetes o comorbilidades.

**Pérdida de peso del 7-10%:** Es la intervención con mayor evidencia. Una reducción del 7% del peso corporal mejora la esteatosis en la mayoría de los pacientes; una reducción del 10% puede resolver la EHNA y reducir la fibrosis. El ritmo óptimo es de 0,5-1 kg por semana; la pérdida rápida de peso puede paradójicamente agravar la inflamación hepática.

**Dieta mediterránea:** Ensayos clínicos han demostrado su superioridad frente a otras dietas en la reducción de la esteatosis hepática, independientemente de la pérdida de peso. Su combinación de ácidos grasos monoinsaturados (aceite de oliva), polifenoles, fibra y bajo índice glucémico impacta directamente los mecanismos fisiopatológicos del HGNA.

**Ejercicio aeróbico y de resistencia:** El ejercicio reduce directamente la grasa hepática a través de múltiples mecanismos: aumenta la oxidación de ácidos grasos, mejora la sensibilidad a la insulina, reduce la lipogénesis de novo y modula la composición de la microbiota. La combinación de aeróbico + resistencia tiene efectos superiores a cualquiera de los dos solos.

**Restricción de fructosa libre:** Eliminar refrescos azucarados, jugos de fruta industriales y alimentos con jarabe de maíz de alta fructosa tiene un impacto medible y rápido sobre la grasa hepática (visible en ecografía en 8-12 semanas).

**Café:** El consumo regular de café (2-3 tazas diarias, preferentemente sin azúcar) se asocia consistentemente en estudios epidemiológicos con menor riesgo de fibrosis hepática en pacientes con HGNA. Los mecanismos propuestos incluyen sus propiedades antioxidantes y antiinflamatorias (ácido clorogénico, diterpenos).

