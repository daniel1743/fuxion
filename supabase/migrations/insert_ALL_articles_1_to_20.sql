### Preguntas frecuentes

**¿Puedo desarrollar intolerancia a la lactosa de repente siendo adulto si antes toleraba bien los lácteos?**
Sí, especialmente si la causa es secundaria a una infección intestinal, una enfermedad celíaca no diagnosticada o el uso de ciertos medicamentos. En estos casos, la intolerancia puede ser temporal y reversible.

**¿Los probióticos pueden ayudar a tolerar mejor la lactosa?**
Algunas cepas bacterianas presentes en yogures y suplementos probióticos (como Lactobacillus bulgaricus y Streptococcus thermophilus) producen lactasa y pueden ayudar a digerir la lactosa en el intestino. Sin embargo, no modifican la producción de lactasa por parte del organismo.

**¿Existe un tratamiento para "curar" la intolerancia genética?**
No. La hipolactasia primaria es una condición genética permanente. El manejo se basa en la restricción dietética adaptada al umbral individual de tolerancia, el uso de suplementos de lactasa enzimática (gotas o comprimidos) antes de las comidas que contengan lactosa, y el consumo de productos lácteos sin lactosa.

**¿La leche sin lactosa es segura para personas con alergia a la proteína de la leche?**
No. La leche sin lactosa sigue conteniendo las proteínas de la leche (caseína, beta-lactoglobulina) que desencadenan la reacción alérgica. Solo se ha eliminado la lactosa, no las proteínas.

