La reacción más común ante el ardor en el pecho es comprar un antiácido en la farmacia más cercana. Esta respuesta es comprensible, porque el alivio es casi inmediato. Pero también es potencialmente engañosa, porque el antiácido trata el síntoma sin tocar el mecanismo que lo genera. Y cuando ese mecanismo no es un exceso de ácido sino una falla de barrera, callar el ácido puede agravar silenciosamente el problema de fondo.

La gastroenterología moderna ha ampliado considerablemente la comprensión del ERGE. Lo que durante décadas se enseñó como un problema simple de "demasiado ácido en el estómago subiendo al esófago" es en realidad un fenómeno multifactorial en el que el ácido juega un papel, sí, pero no necesariamente el papel protagónico que se le asignó.

Entender cómo funciona realmente el sistema de válvulas del tracto digestivo —y por qué falla— puede cambiar radicalmente la manera en que una persona gestiona este problema a largo plazo.

---

### Anatomía funcional: el sistema de dos válvulas

El esófago es un tubo muscular de aproximadamente 25 centímetros que transporta los alimentos desde la boca hasta el estómago. En su extremo inferior existe un músculo especializado llamado **esfínter esofágico inferior (EEI)**: una banda de músculo liso que permanece contraída en reposo, creando una zona de alta presión que impide que el contenido ácido del estómago suba hacia el esófago.

A diferencia del esfínter anal, el EEI no está bajo control voluntario. Responde a señales mecánicas (la distensión del esófago durante la deglución) y señales químicas (la acidez gástrica es uno de los principales estímulos que lo mantiene contraído). Además, existe una segunda línea de defensa: el diafragma, que rodea al esófago y añade presión externa al EEI.

Cuando el sistema funciona correctamente, el EEI solo se relaja para dejar pasar el alimento hacia el estómago y, brevemente, para liberar gases en el eructo fisiológico. El resto del tiempo permanece sellado.

#### La analogía del globo bajo presión

Imagina el estómago como un globo resistente que contiene un líquido altamente ácido. El EEI es el nudo en la parte superior de ese globo. Si el globo está sometido a presión externa —como ocurre en la obesidad visceral, el embarazo, una hernia de hiato o la distensión por gases intestinales— el líquido tiende a subir hacia el nudo. Si el nudo está bien apretado, nada pasa. Pero si el nudo es débil —por relajación del tono muscular del EEI— o si la presión es suficientemente alta, el líquido se escapa hacia el esófago.

Lo que hace este sistema particularmente complejo es que el "nudo" (el EEI) depende, entre otras cosas, de la acidez del propio líquido que contiene el globo. El ácido clorhídrico del estómago no solo digiere proteínas: también actúa como señal química que indica al EEI que debe permanecer contraído. Si el ácido es insuficiente (hipoclorhidria), la señal es débil, el esfínter pierde tono, y paradójicamente, el reflujo puede empeorar aunque haya menos ácido disponible.

