### Preguntas frecuentes

**¿El SII puede confundirse con otras enfermedades?**
Sí, y es una de las razones por las que el diagnóstico requiere descartar activamente otras patologías. Las que más se solapan sintomáticamente con el SII son: Enfermedad Inflamatoria Intestinal (Crohn y Colitis Ulcerosa), celiaquía, intolerancia a la lactosa, SIBO, y en mujeres, la endometriosis y la enfermedad inflamatoria pélvica.

**¿Los probióticos funcionan para el SII?**
La evidencia es moderada y muy dependiente de la cepa. *Bifidobacterium infantis* 35624 mostró reducción del dolor y meteorismo en ensayos clínicos. Combinaciones de *Lactobacillus* y *Bifidobacterium* también tienen evidencia en algunos subtipos. La clave es que no todos los probióticos son iguales para el SII: la eficacia es cepa-específica, no es un efecto de clase.

**¿La dieta FODMAP es segura a largo plazo?**
Su fase de eliminación estricta no está diseñada para el largo plazo. Mantenida indefinidamente, puede reducir la diversidad de la microbiota al privar a las bacterias beneficiosas de sus sustratos preferidos. El objetivo es siempre llegar a la fase de personalización, que maximiza los alimentos tolerados y minimiza la restricción innecesaria.

**¿El SII aumenta el riesgo de cáncer colorrectal?**
No. Los estudios epidemiológicos a largo plazo no han encontrado mayor riesgo de cáncer colorrectal en pacientes con SII respecto a la población general. Sin embargo, los síntomas del SII pueden enmascarar síntomas iniciales de otras patologías, por lo que el seguimiento médico regular es importante.

**¿El SII afecta a la salud mental o es al revés?**
Ambas direcciones son reales. La ansiedad y la depresión son comorbilidades muy prevalentes en el SII (presentes en el 40-60% de los pacientes en algunas series). La relación es bidireccional a través del eje intestino-cerebro: la disbiosis y la hipersensibilidad visceral del SII pueden contribuir a síntomas de ansiedad, y la ansiedad puede empeorar la hipersensibilidad visceral y la motilidad. El abordaje que trata ambas dimensiones simultáneamente tiene los mejores resultados.

