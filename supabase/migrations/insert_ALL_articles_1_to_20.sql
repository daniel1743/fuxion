### La microbiota como productora de señales cerebrales

Aquí es donde el eje intestino-cerebro adquiere su dimensión más fascinante y más relevante para la salud pública: las bacterias que viven en tu intestino producen activamente sustancias que modifican cómo funciona tu cerebro.

#### Serotonina: el gran malentendido

El intestino produce aproximadamente el **90-95% de la serotonina total del organismo**. Esta cifra suele interpretarse de forma errónea como "el intestino fabrica la serotonina que nos hace felices". La realidad es más matizada.

La serotonina intestinal (producida por las células enterocromafines del epitelio, estimuladas en parte por bacterias) no cruza la barrera hematoencefálica. Su función en el intestino es regular la motilidad, coordinar los reflejos digestivos y activar las fibras aferentes del nervio vago. El cerebro debe sintetizar su propia serotonina a partir del triptófano, un aminoácido esencial.

Sin embargo, la microbiota influye indirectamente en la serotonina cerebral de dos formas críticas:
1. Regula la disponibilidad de **triptófano** libre en el plasma (la materia prima para la síntesis cerebral de serotonina).
2. Modula la enzima **IDO** (indoleamina 2,3-dioxigenasa) que puede desviar el triptófano hacia la vía de la kinurenina (inflamatoria) en lugar de hacia la vía de la serotonina. La disbiosis favorece esta desviación, y se investiga como mecanismo en la depresión.

#### GABA microbiano

*Lactobacillus rhamnosus* y otras especies producen **GABA** (ácido gamma-aminobutírico), el principal neurotransmisor inhibidor del sistema nervioso central. Aunque el GABA producido en el intestino tampoco cruza directamente la barrera hematoencefálica, activa receptores vagales que modulan la ansiedad y la respuesta al estrés. Estudios en modelos animales han mostrado que esta producción microbiana de GABA reduce conductas de ansiedad, aunque los ensayos clínicos en humanos son aún preliminares.

#### Ácidos grasos de cadena corta (AGCC) y cerebro

El butirato, el propionato y el acetato —producidos por la fermentación de fibra prebiótica— tienen efectos cerebrales documentados: el butirato actúa como inhibidor de las histonas deacetilasas (HDACi), modulando la expresión génica en el cerebro y potencialmente influyendo en la neuroplasticidad y la neuroinflamación.

