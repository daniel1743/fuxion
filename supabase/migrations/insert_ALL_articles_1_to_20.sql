### La dieta FODMAP: la intervención dietética con más evidencia

Los **FODMAPs** (Fermentable Oligosaccharides, Disaccharides, Monosaccharides And Polyols) son carbohidratos fermentables de cadena corta que comparten dos características problemáticas para personas con SII:

1. **Atraen agua por osmosis** al intestino delgado, aumentando el volumen luminal y la urgencia.
2. **Son fermentados rápidamente** por las bacterias del colon, produciendo grandes volúmenes de gas que distienden el intestino hipersensible.

| Categoría FODMAP | Moléculas | Alimentos con alto contenido |
| :--- | :--- | :--- |
| **Oligosacáridos** | Fructanos, GOS | Trigo, ajo, cebolla, puerro, legumbres |
| **Disacáridos** | Lactosa | Leche, yogur, quesos frescos |
| **Monosacáridos** | Fructosa libre (>glucosa) | Manzana, mango, miel, jarabe de maíz |
| **Polioles** | Sorbitol, manitol, xilitol | Aguacate, champiñones, edulcorantes artificiales |

La dieta baja en FODMAPs se implementa en tres fases bajo supervisión de un dietista-nutricionista especializado:
1. **Fase de eliminación** (2-6 semanas): restricción estricta de todos los FODMAPs para evaluar la respuesta sintomática.
2. **Fase de reintroducción** (6-8 semanas): reintroducción sistemática de cada grupo de FODMAP para identificar cuáles son problemáticos en cada individuo.
3. **Fase de personalización**: dieta de largo plazo adaptada a los FODMAPs tolerados individualmente.

> **Nota importante:** La dieta FODMAP no debe realizarse de forma autodirigida sin diagnóstico previo de SII. Su restricción estricta, mantenida de forma indefinida, puede reducir la diversidad de la microbiota al privar de prebióticos esenciales a las bacterias beneficiosas.

