### La cascada inmunológica: del primer contacto a la anafilaxia

Para entender cómo se desencadena una reacción alérgica IgE, es útil visualizar un proceso que ocurre en dos fases distintas.

**Fase 1: Sensibilización (el primer encuentro silencioso)**

La primera vez que una persona consume un alimento alergénico, su sistema inmunológico puede "decidir" tratarlo como una amenaza. Las células presentadoras de antígeno (como las células dendríticas) capturan fragmentos de la proteína alimentaria y los presentan a los linfocitos T. Estos, a su vez, activan a los linfocitos B, que comienzan a producir grandes cantidades de anticuerpos IgE específicos contra esa proteína. Estos anticuerpos viajan por el torrente sanguíneo y se adhieren a la superficie de los mastocitos (presentes en tejidos como la piel, el tracto respiratorio y el digestivo) y los basófilos (células circulantes). En esta fase, la persona no presenta síntomas, pero su sistema inmunológico ha quedado "armado" y listo para responder.

**Fase 2: Desencadenamiento (la reacción explosiva)**

Cuando la persona vuelve a consumir el mismo alimento, la proteína alergénica se encuentra directamente con los anticuerpos IgE anclados en los mastocitos. Este encuentro provoca que los mastocitos se "degranulen", liberando una avalancha de mediadores químicos, principalmente histamina, pero también leucotrienos, prostaglandinas y citoquinas. Es esta liberación masiva la que genera los síntomas característicos: vasodilatación (enrojecimiento, urticaria), aumento de la permeabilidad vascular (edema, angioedema), contracción del músculo liso bronquial (dificultad respiratoria, sibilancias) y estimulación de las terminaciones nerviosas (picor, dolor abdominal).

### Los alérgenos más frecuentes: una cuestión de geografía y edad

Aunque teóricamente cualquier proteína alimentaria podría actuar como alérgeno, la evidencia epidemiológica ha identificado un grupo reducido de alimentos responsables de la mayoría de las reacciones.

- **En niños:** Leche de vaca, huevo, cacahuete, soja y trigo son los desencadenantes más comunes. Afortunadamente, muchas alergias a la leche y al huevo tienden a resolverse con la edad.
- **En adultos:** Cacahuete, frutos secos (nuez, almendra, anacardo), pescado, marisco y frutas frescas (especialmente en el contexto del síndrome de alergia oral) son los principales responsables.
- **Variabilidad geográfica:** En países mediterráneos, la alergia al melocotón (mediada por la proteína LTP) es particularmente prevalente, mientras que en Asia oriental, el arroz y las semillas de sésamo son causas frecuentes.

### Diagnóstico diferencial: más allá de la IgE

Uno de los errores más comunes en la práctica clínica y en la automedicación es atribuir cualquier síntoma digestivo o cutáneo tras una comida a una alergia IgE. Existen múltiples condiciones que pueden simular una alergia alimentaria:

- **Síndrome de alergia oral (SAO):** Ocurre cuando proteínas de frutas y verduras crudas, similares a las del polen, desencadenan picor y hormigueo localizado en labios, boca y garganta. Generalmente no progresa a anafilaxia y se resuelve al cocinar el alimento.
- **Intolerancia a la lactosa:** Causada por déficit de lactasa, provoca síntomas digestivos (distensión, diarrea) sin mediación inmunológica.
- **Enfermedad celíaca:** Aunque involucra al sistema inmunológico, es una reacción autoinmune mediada por linfocitos T, no por IgE, y sus síntomas son predominantemente digestivos y sistémicos a largo plazo.
- **Síndrome del intestino irritable (SII):** Los síntomas pueden solaparse con los de una alergia alimentaria, pero no existe un mecanismo inmunológico identificable.

### Desmitificación Científica

- **Mito:** "Las pruebas de IgG para alimentos pueden diagnosticar alergias alimentarias."
- **Realidad:** La presencia de anticuerpos IgG contra alimentos indica exposición y tolerancia inmunológica, no alergia. Las guías clínicas internacionales (EAACI, AAAAI) desaconsejan firmemente el uso de pruebas de IgG para el diagnóstico de alergias alimentarias, ya que carecen de validez clínica y pueden llevar a restricciones dietéticas innecesarias.
- **Mito:** "Si un test de IgE específica da positivo, significa que soy alérgico a ese alimento."
- **Realidad:** Una prueba de IgE positiva indica sensibilización, no necesariamente alergia clínica. Muchas personas tienen IgE detectable contra un alimento sin experimentar síntomas al consumirlo. El diagnóstico definitivo requiere correlación con la historia clínica y, en casos dudosos, una prueba de provocación oral controlada.
- **Mito:** "Las alergias alimentarias se pueden curar con dietas de desintoxicación o suplementos."
- **Realidad:** Actualmente no existe cura para las alergias alimentarias IgE. El manejo estándar se basa en la evitación estricta del alérgeno y el tratamiento de las reacciones agudas (antihistamínicos, adrenalina). La inmunoterapia oral (OIT) es una estrategia emergente que busca inducir tolerancia, pero debe realizarse bajo estricta supervisión médica y no está exenta de riesgos.

### Guía de Advertencia: Cuándo acudir a un especialista (Red Flags)

Es fundamental buscar evaluación médica urgente o programar una consulta con un alergólogo si se presentan las siguientes situaciones:

- **Reacción sistémica inmediata:** Aparición de urticaria generalizada, hinchazón de labios, lengua o garganta, dificultad para respirar, sibilancias, mareo o pérdida de conciencia tras la ingesta de un alimento. Esto constituye una emergencia médica (anafilaxia) y requiere atención inmediata.
- **Síntomas recurrentes sin causa aparente:** Episodios repetidos de dolor abdominal, diarrea, vómitos o erupciones cutáneas que se relacionan temporalmente con las comidas.
- **Antecedentes de reacción grave previa:** Cualquier persona que haya experimentado una reacción alérgica grave debe ser evaluada por un alergólogo para identificar el alérgeno responsable y recibir un plan de acción, incluyendo la prescripción de autoinyectores de adrenalina.
- **Crecimiento o desarrollo alterado en niños:** Si un niño presenta retraso en el crecimiento, pérdida de peso o rechazo persistente a ciertos alimentos, se debe descartar una alergia alimentaria subyacente.
- **Sospecha de alergia múltiple:** Cuando se sospecha alergia a más de un alimento, la evaluación especializada es crucial para evitar restricciones dietéticas excesivas que puedan comprometer el estado nutricional.

### Preguntas frecuentes

**¿Las alergias alimentarias pueden desaparecer con la edad?**
Sí, especialmente las alergias a la leche de vaca, al huevo, al trigo y a la soja. Se estima que entre el 50-80% de los niños superan estas alergias hacia la adolescencia. En cambio, las alergias al cacahuete, frutos secos, pescado y marisco tienden a persistir durante toda la vida.

**¿Es seguro consumir alimentos procesados que "pueden contener trazas" de un alérgeno?**
No existe una respuesta universal. Para personas con alergias graves, incluso trazas mínimas pueden desencadenar anafilaxia. La decisión debe basarse en la gravedad de la alergia, la historia de reacciones previas y la recomendación del alergólogo. En general, se recomienda evitar cualquier producto que no garantice explícitamente la ausencia del alérgeno.

**¿La lactancia materna protege contra el desarrollo de alergias alimentarias?**
La evidencia actual sugiere que la lactancia materna exclusiva durante los primeros 4-6 meses puede tener un efecto protector modesto, pero no elimina por completo el riesgo. Las guías actuales recomiendan la introducción temprana (alrededor de los 4-6 meses) de alimentos alergénicos como el cacahuete y el huevo, especialmente en niños con alto riesgo (eczema severo o alergia al huevo), ya que esto se ha asociado con una reducción significativa del riesgo de desarrollar alergia a estos alimentos.

### Conclusión

Las alergias alimentarias mediadas por IgE representan un desafío clínico creciente que requiere un enfoque diagnóstico riguroso y un manejo multidisciplinario. La clave para una atención segura y efectiva reside en distinguir claramente entre sensibilización y alergia clínica, evitar restricciones dietéticas innecesarias basadas en pruebas no validadas, y proporcionar a los pacientes las herramientas necesarias para reconocer y tratar las reacciones agudas. La investigación continúa avanzando en estrategias de inmunoterapia y prevención, ofreciendo esperanza para un futuro con menos limitaciones dietéticas.

