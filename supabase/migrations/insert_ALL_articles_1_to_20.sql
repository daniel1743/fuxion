### Los ácidos grasos de cadena corta: el tesoro que fabrica la microbiota

Cuando la fibra soluble y el almidón resistente son fermentados en el colon, las bacterias producen tres ácidos grasos de cadena corta principales: **butirato, propionato y acetato**. Estas moléculas pequeñas tienen efectos que van mucho más allá del colon:

**Butirato:**
- Es la principal fuente de energía de los colonocitos (células del colon). Sin butirato, las células del colon entran en apoptosis.
- Regula la expresión génica a través de la inhibición de las histonas deacetilasas (HDAC), con potenciales efectos antiinflamatorios y anticancerígenos.
- Fortalece las uniones estrechas del epitelio, reduciendo la permeabilidad intestinal.
- Activa el sistema inmune regulatorio del intestino (células T reguladoras).

**Propionato:**
- Es captado por el hígado y utilizado en la gluconeogénesis.
- Reduce la síntesis hepática de colesterol.
- Activa receptores de señalización que regulan el apetito y la sensibilidad a la insulina.

**Acetato:**
- Es el AGCC más abundante.
- Cruza la barrera hematoencefálica y puede afectar el comportamiento alimentario a nivel central.
- Sirve de sustrato energético para otros órganos.

