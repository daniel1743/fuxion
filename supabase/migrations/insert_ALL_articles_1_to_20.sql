### ¿Qué es exactamente el SIBO y por qué importa entenderlo?

El intestino delgado sano contiene una cantidad relativamente baja de bacterias: menos de 10³ unidades formadoras de colonias por mililitro (UFC/mL) en el yeyuno proximal. El colon, por contraste, alberga entre 10¹¹ y 10¹² UFC/mL. Cuando el recuento bacteriano en el intestino delgado supera las 10⁵ UFC/mL, los investigadores lo clasifican formalmente como sobrecrecimiento.

Esta diferencia numérica tiene consecuencias metabólicas directas. Las bacterias del intestino delgado compiten con el huésped por los nutrientes, interfieren en la emulsificación de las grasas al deconjugar las sales biliares prematuramente, y fermentan los carbohidratos antes de que el epitelio intestinal pueda absorberlos, produciendo gases que dilatan el intestino desde adentro.

#### La analogía del río y el estanque

Imagina el intestino delgado como un río cristalino en el que los peces (nutrientes) se mueven libremente hacia sus destinos. El colon sería un estanque de procesamiento aguas abajo, donde las bacterias descomponen los residuos que el río dejó pasar.

Entre ambos existe una compuerta física —la válvula ileocecal— y un mecanismo de limpieza periódica llamado Complejo Motor Migratorio (CMM): ondas de contracción que barren el intestino delgado cada 90-120 minutos durante el ayuno, expulsando bacterias, células muertas y residuos hacia el colon. En el SIBO, uno o ambos sistemas de control fallan. La compuerta pierde presión y las bacterias del estanque migran río arriba. Las ondas de limpieza se reducen o desaparecen. El río se contamina y los peces —los nutrientes— dejan de llegar a su destino.

