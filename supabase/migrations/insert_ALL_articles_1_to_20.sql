### El esófago de Barrett: cuando el reflujo cronifica y las células cambian

Una de las complicaciones más relevantes del ERGE no controlado es el **esófago de Barrett**: una condición en la que las células del esófago inferior, sometidas de forma crónica al ácido gástrico, se transforman en un tipo celular similar al del intestino (metaplasia intestinal especializada). Esta transformación, aunque no es cáncer, es considerada una lesión precancerosa que requiere seguimiento endoscópico periódico.

La prevalencia del esófago de Barrett en pacientes con ERGE crónico oscila entre el 10 y el 15%, y es significativamente más alta en hombres mayores de 50 años, fumadores y pacientes con obesidad. Su detección temprana mediante endoscopia es fundamental para prevenir la progresión hacia el adenocarcinoma esofágico.

