### Un azúcar que divide a la humanidad

La leche materna es el primer alimento de prácticamente todos los mamíferos. Su principal carbohidrato, la lactosa, proporciona aproximadamente el 40% de la energía que necesita un recién nacido. Sin embargo, al destetarse, la mayoría de las especies —incluidos los humanos— experimentan una reducción natural en la producción de lactasa, la enzima encargada de descomponer este disacárido. Este fenómeno, lejos de ser una anomalía, representa el patrón evolutivo ancestral. La capacidad de digerir lactosa en la edad adulta es, en realidad, una mutación genética relativamente reciente que se extendió en poblaciones con tradición ganadera. Comprender esta paradoja evolutiva es esencial para distinguir entre lo que es genético y lo que es adquirido.

### ¿Qué ocurre cuando la lactosa no se digiere?

Para entender la intolerancia, primero debemos comprender el proceso normal. La lactosa es un disacárido formado por glucosa y galactosa. Para ser absorbida, necesita ser hidrolizada por la lactasa-florizina hidrolasa, una enzima ubicada en el borde en cepillo de los enterocitos del intestino delgado.

Cuando la actividad de esta enzima es insuficiente, la lactosa no digerida continúa su tránsito hacia el colon. Allí, las bacterias de la microbiota la fermentan, produciendo gases (hidrógeno, metano, dióxido de carbono) y ácidos grasos de cadena corta. Este proceso genera los síntomas característicos: distensión abdominal, flatulencias, dolor tipo cólico y, en algunos casos, diarrea osmótica.

### La analogía de la fábrica de reciclaje

Imagina una fábrica de reciclaje que recibe grandes cantidades de un material específico, digamos plástico tipo PET. La línea de producción cuenta con una máquina especializada (la lactasa) que descompone ese plástico en sus componentes básicos para que puedan reutilizarse. Si la máquina funciona a baja capacidad o directamente está averiada, el plástico sin procesar se acumula en la cinta transportadora y termina desbordándose hacia el vertedero (el colon). Allí, otros microorganismos (las bacterias intestinales) intentan descomponerlo, pero lo hacen de forma desordenada, generando gases y residuos que irritan el entorno. El resultado: una fábrica que se satura, se hincha y produce molestias.

### Los dos orígenes de la deficiencia de lactasa

La clasificación clínica distingue tres tipos principales de deficiencia de lactasa, aunque las dos primeras son las más relevantes para el público general.

