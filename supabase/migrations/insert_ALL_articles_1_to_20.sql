### Los psicobióticos: el campo emergente más prometedor

En 2013, los investigadores Ted Dinan y John Cryan acuñaron el término **psicobiótico** para referirse a microorganismos vivos que, cuando se ingieren en cantidades adecuadas, producen beneficios en la salud mental de personas con trastornos psiquiátricos. El concepto se ha ampliado para incluir también los prebióticos que alimentan a las bacterias con efectos psicológicos.

La investigación en psicobióticos está en una fase activa pero aún preliminar. Algunos hallazgos relevantes:

- Un estudio publicado en *Gastroenterology* (Pinto-Sanchez et al., 2017) mostró que *Lactobacillus rhamnosus* JB-1 redujo significativamente los síntomas de ansiedad y depresión en pacientes con SII.
- Una revisión sistemática de 2019 en *General Psychiatry* encontró que la suplementación con probióticos redujo los síntomas de depresión en comparación con placebo en 34 ensayos controlados.
- Sin embargo, la heterogeneidad de las cepas, las dosis y las poblaciones estudiadas hace que las guías clínicas aún no recomienden los probióticos como tratamiento estándar para los trastornos mentales.

> **Nota importante:** Los psicobióticos no reemplazan el tratamiento farmacológico ni psicoterapéutico para los trastornos de salud mental. Son un campo de investigación activo, no una terapia validada de primera línea.

---

### Estimulación del nervio vago: una frontera terapéutica

Dado el papel central del nervio vago en el eje intestino-cerebro, ha surgido un creciente interés en técnicas que fortalezcan su tono. La **estimulación del nervio vago** (ENV) mediante dispositivos implantados ya es una terapia aprobada para la epilepsia refractaria y la depresión resistente al tratamiento en varios países.

Paralelamente, técnicas no invasivas han mostrado resultados prometedores en modelos animales e investigación preliminar en humanos:
- **Respiración lenta y diafragmática** (6 respiraciones por minuto): activa el sistema vagal parasimpático.
- **Exposición a frío** (agua fría en la cara o duchas frías breves): activa el reflejo de buceo y estimula el vago.
- **Ejercicio aeróbico moderado:** Aumenta el tono vagal y mejora la variabilidad de la frecuencia cardíaca, un marcador del tono vagal.
- **Cantar, tararear, rezar en voz alta:** El nervio vago inerva las cuerdas vocales; su activación con estas prácticas tiene respaldo fisiológico.

