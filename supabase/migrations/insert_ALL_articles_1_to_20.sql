### Desmitificación Científica

**Mito 1:** "Los suplementos de fibra en polvo (psyllium, inulina) equivalen a comer verduras."
**Realidad:** Los suplementos de fibra son una herramienta útil para alcanzar objetivos cuantitativos, pero no replican la complejidad de la matriz alimentaria vegetal. Un alimento integral como una manzana no solo aporta pectina: ofrece vitaminas, quercetina, ácido clorogénico, agua y una estructura física que ralentiza la digestión de forma diferente a un polvo disuelto. Los suplementos complementan; los alimentos son la base insustituible.

**Mito 2:** "Toda la fibra es igual para el estreñimiento."
**Realidad:** Depende del tipo de estreñimiento. La fibra insoluble (celulosa del salvado de trigo, vegetales) es eficaz para acelerar el tránsito en el estreñimiento funcional normal. Sin embargo, en pacientes con estreñimiento por tránsito lento severo o disfunción del suelo pélvico, añadir fibra sin resolver el mecanismo subyacente puede empeorar la distensión sin mejorar la evacuación. El tipo de fibra debe adaptarse al tipo de estreñimiento bajo supervisión médica.

**Mito 3:** "La fibra interfiere con la absorción de todos los nutrientes."
**Realidad:** La fibra soluble reduce moderadamente la absorción de algunos minerales como hierro y zinc cuando se consume en cantidades muy elevadas o con suplementos de hierro en el mismo momento. Sin embargo, a dosis habituales (25-38g/día) provenientes de alimentos integrales, el efecto inhibidor es mínimo y ampliamente compensado por los beneficios globales. El consejo de espaciar los suplementos de hierro de las comidas ricas en fibra es prudente pero no implica que la fibra sea perjudicial para la nutrición en general.

