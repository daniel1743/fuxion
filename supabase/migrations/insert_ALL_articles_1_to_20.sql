| **Síntomas sistémicos** | Sí: anemia, osteoporosis, dermatitis herpetiforme | Sí: niebla mental, fatiga, cefalea | Sí: urticaria, angioedema, anafilaxia |
| **Tratamiento** | Dieta estricta libre de gluten de por vida | Dieta libre de gluten (o FODMAPs) mientras haya síntomas | Evitar el trigo; adrenalina en casos graves |
| **Riesgo de no diagnosticar** | Alto: linfoma intestinal, infertilidad, osteoporosis severa | Moderado: malnutrición, impacto en calidad de vida | Alto: riesgo de anafilaxia |

---

### Las manifestaciones extradigestivas que se pierden con frecuencia

Uno de los mayores errores en el diagnóstico de la celiaquía es buscarla exclusivamente en el contexto de síntomas digestivos clásicos (diarrea, distensión, malabsorción evidente). En realidad, la EC es una enfermedad sistémica que puede presentarse —o presentarse exclusivamente— con manifestaciones extradigestivas:

- **Dermatitis Herpetiforme:** Erupción cutánea intensamente pruriginosa con vesículas simétricas en codos, rodillas y glúteos. Es la manifestación cutánea de la EC y por sí sola es diagnóstica en contexto adecuado.
- **Osteoporosis precoz:** La malabsorción de calcio y vitamina D, aunque sea silenciosa, destruye la masa ósea de forma acumulativa. Se diagnostica la EC en pacientes jóvenes con fracturas por fragilidad.
- **Anemia ferropénica refractaria:** Que no responde al tratamiento oral con hierro porque el hierro no se absorbe correctamente en un intestino delgado con vellosidades atróficas.
- **Infertilidad y abortos espontáneos recurrentes:** La EC no controlada altera el estado nutricional y el equilibrio hormonal de formas que impactan la fertilidad.
- **Neuropatía periférica y ataxia celíaca:** Síntomas neurológicos por déficit de vitamina B12 y folato o, en algunos casos, por mecanismos autoinmunes directos sobre el tejido nervioso.
- **Retraso del crecimiento** e **hipolactasia secundaria** en niños.

---

### El diagnóstico: por qué el orden importa tanto

El error más costoso que comete un paciente con sospecha de celiaquía es eliminar el gluten antes de hacerse las pruebas diagnósticas. La lógica parece razonable —si me siento mejor sin gluten, debo ser celíaco—, pero destruye la posibilidad de obtener un diagnóstico formal.

**El proceso diagnóstico correcto:**
1. **Serología:** Anticuerpos anti-transglutaminasa tisular IgA (anti-tTG IgA) + IgA total (para descartar déficit de IgA, que falsearía el resultado). En niños, anti-péptido de gliadina deaminada (anti-DGP).
2. **Genotipado HLA:** Determinar si el paciente tiene HLA-DQ2 o DQ8. Si es negativo, prácticamente descarta la celiaquía.
3. **Endoscopia con biopsia duodenal:** Gold standard. Se deben tomar al menos 4-6 biopsias de diferentes porciones del duodeno para aumentar la sensibilidad diagnóstica.
4. **Respuesta a la dieta sin gluten:** La mejoría histológica y serológica tras 6-12 meses de dieta estricta confirma el diagnóstico.

Todo este proceso es inválido si el paciente ha eliminado el gluten previamente. Las vellosidades se recuperan y los anticuerpos desaparecen, dando resultados falsos negativos. Si ya has eliminado el gluten, el especialista puede indicar una provocación controlada con gluten antes de las pruebas.

---

### Desmitificación Científica

**Mito 1:** "Si llevo meses sin gluten y me siento bien, ya soy celíaco confirmado."
**Realidad:** La mejoría sin gluten es compatible con la EC, la SGNC, la sensibilidad a los FODMAPs del trigo o simplemente con una mejora general de la dieta al eliminar ultraprocesados que contienen gluten. Solo la biopsia duodenal (con el paciente consumiendo gluten) confirma o descarta la EC. Un diagnóstico no confirmado puede llevar a manejar una enfermedad grave de forma inadecuada.

**Mito 2:** "La dieta sin gluten es más saludable para cualquier persona."
**Realidad:** En personas sin EC ni SGNC, la dieta sin gluten no aporta beneficios documentados y puede ser perjudicial: los productos procesados "sin gluten" frecuentemente tienen mayor contenido de azúcar, grasas saturadas y sodio para compensar la textura, y menor contenido de fibra, vitaminas del grupo B y hierro.

**Mito 3:** "Si tengo un familiar celíaco, ya sé que tengo la enfermedad."
**Realidad:** Tener un familiar de primer grado celíaco aumenta el riesgo al 10-15% (versus el 1% de la población general). Justifica hacer el cribado, pero no el diagnóstico. Los familiares de primer grado deben someterse a serología periódica, pero el diagnóstico siempre requiere confirmación histológica.

---

### ¿Cuándo consultar a un profesional de la salud?

Solicite evaluación especializada en gastroenterología si presenta:

- Síntomas digestivos crónicos (diarrea, distensión, dolor) que no se han investigado formalmente.
- Anemia ferropénica sin causa aparente o resistente al tratamiento con hierro oral.
- Osteoporosis a una edad inusualmente joven (especialmente en mujeres premenopáusicas).
- Erupción cutánea pruriginosa con vesículas en áreas simétricas (codos, rodillas, glúteos).
- Infertilidad sin causa identificada o abortos espontáneos repetidos.
- Familiar de primer grado con diagnóstico confirmado de celiaquía.
- Diagnóstico de diabetes tipo 1 o tiroiditis autoinmune (condiciones con mayor prevalencia de EC asociada).
- Retraso del crecimiento o pubertad retrasada en niños y adolescentes.

