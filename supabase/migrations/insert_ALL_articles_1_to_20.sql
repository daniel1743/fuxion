### Genética: el mapa de la persistencia de lactasa

La capacidad de digerir lactosa en la edad adulta se conoce como persistencia de lactasa. Este rasgo está determinado por variantes genéticas en una región reguladora ubicada aguas arriba del gen LCT, específicamente en el gen MCM6. La variante más estudiada en poblaciones europeas es el polimorfismo -13910C>T (rs4988235). Las personas con el genotipo TT o CT suelen mantener altos niveles de lactasa durante toda la vida. En cambio, quienes presentan el genotipo CC experimentan la disminución fisiológica normal tras el destete.

La distribución geográfica de estas variantes es fascinante y refleja la historia de la domesticación de animales. Las poblaciones del norte de Europa, ciertas regiones de África del Este (como los pastores masái) y algunas comunidades del Medio Oriente presentan frecuencias elevadas de persistencia de lactasa. Por el contrario, la mayoría de las poblaciones de Asia Oriental, África subsahariana (excepto pastores) y América indígena presentan frecuencias muy bajas.

### Adquirida: cuando el intestino se lesiona

La intolerancia adquirida es secundaria a una agresión directa sobre la mucosa intestinal. Dado que la lactasa es la enzima del borde en cepillo más sensible y la que se regenera más lentamente, cualquier daño epitelial puede reducir temporalmente su actividad.

Las causas más frecuentes incluyen:
- **Gastroenteritis aguda:** Especialmente las de origen viral (rotavirus, norovirus) o parasitario (Giardia lamblia). La intolerancia puede persistir semanas después de la infección.
- **Enfermedad celíaca:** La exposición al gluten en personas genéticamente predispuestas genera una respuesta autoinmune que daña las vellosidades intestinales, reduciendo drásticamente la superficie de absorción y la producción de lactasa.
- **Enfermedad inflamatoria intestinal (Crohn):** La inflamación crónica de la mucosa afecta la función de los enterocitos.
- **Medicamentos:** El uso prolongado de antibióticos (que alteran la microbiota) o AINEs (que dañan la mucosa) puede contribuir a una reducción transitoria de la actividad enzimática.

### Desmitificación Científica

- **Mito:** La intolerancia a la lactosa significa que no se puede consumir ningún producto lácteo.
- **Realidad:** Muchas personas con hipolactasia primaria toleran pequeñas cantidades de lactosa (hasta 12-15 gramos por dosis, equivalentes a 250-300 ml de leche) si se distribuyen a lo largo del día y se consumen junto con otros alimentos. Además, los quesos curados y los yogures con cultivos vivos contienen menos lactosa y suelen ser mejor tolerados.

