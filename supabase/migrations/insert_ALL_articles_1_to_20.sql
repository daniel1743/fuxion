### El microbioma y la inflamación sistémica: los órganos que están lejos pero sienten el impacto

Uno de los hallazgos más sorprendentes de la investigación microbiológica de los últimos años es que la disbiosis intestinal no es un problema exclusivamente digestivo. Sus efectos, mediados principalmente por las endotoxinas y los metabolitos microbianos, alcanzan órganos aparentemente distantes:

**Cerebro:** A través del eje intestino-cerebro (nervio vago, señales hormonales y metabolitos), la disbiosis se asocia con mayor prevalencia de depresión, ansiedad y deterioro cognitivo. La neuroinflamación mediada por LPS es uno de los mecanismos propuestos.

**Hígado:** El 70% del flujo portal (la sangre que drena el intestino) llega directamente al hígado. Los LPS de una microbiota disbiótica saturan el hígado, activando células de Kupffer y contribuyendo a la inflamación hepática de bajo grado. Se investiga su rol en el Hígado Graso No Alcohólico (HGNA).

**Piel:** La disbiosis intestinal se ha asociado con dermatitis atópica, acné y psoriasis a través de mecanismos inmunológicos compartidos entre la mucosa intestinal y la piel (eje intestino-piel).

**Tejido adiposo y metabolismo:** La microbiota modula la extracción de energía de los alimentos, la sensibilidad a la insulina y la producción de hormonas del apetito como la GLP-1 y el péptido YY. Una microbiota disbiótica puede favorecer mayor extracción calórica y mayor resistencia a la insulina.

