### El segundo cerebro: anatomía de una metáfora que resultó ser literal

El sistema nervioso entérico (SNE) es una red neuronal autónoma que tapiza el tracto gastrointestinal desde el esófago hasta el ano. Contiene entre 400 y 600 millones de neuronas —más que la médula espinal— organizadas en dos plexos nerviosos (plexo de Meissner y plexo de Auerbach) que coordinan la motilidad, la secreción, el flujo sanguíneo local y la respuesta inmune intestinal.

El SNE puede funcionar de forma completamente autónoma, incluso si el nervio vago es seccionado quirúrgicamente. Esta independencia funcional es lo que llevó al neurogastroenterólogo Michael Gershon, en su libro *The Second Brain* (1998), a acuñar el término que hoy es ya parte del lenguaje científico estándar.

Sin embargo, "segundo cerebro" no significa igual al primero. El sistema nervioso entérico no tiene conciencia, no planea, no razona. Su especialidad es la percepción visceral y la regulación autonómica del tracto digestivo. Pero su comunicación constante con el sistema nervioso central —especialmente a través del nervio vago— lo convierte en un modulador activo del estado cerebral, y no en un simple ejecutor de sus órdenes.

