### ¿Cuándo consultar a un profesional de la salud?

Busque evaluación médica antes de aumentar bruscamente la fibra, o si presenta:

- Antecedentes de obstrucción intestinal recurrente o diagnóstico de estenosis intestinal (como en la enfermedad de Crohn).
- Dolor abdominal tipo cólico severo reproducible tras el consumo de vegetales crudos o legumbres.
- Cambios persistentes en el calibre de las heces (heces muy finas o en cinta) de más de 2-3 semanas de duración.
- Sangre en las heces o sangrado rectal al aumentar el consumo de fibra.
- Crisis de enfermedad inflamatoria intestinal activa (Crohn o Colitis Ulcerosa): el aumento de fibra en fases activas puede no ser adecuado sin supervisión.
- Disfagia esofágica en pacientes que toman psyllium o suplementos en polvo sin suficiente líquido.

