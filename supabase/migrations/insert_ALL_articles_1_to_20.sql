### Conclusión

La fibra dietética es, en sentido estricto, el alimento de nuestras bacterias. Y las bacterias son, en un sentido cada vez más amplio, parte de nosotros. La distinción entre soluble e insoluble no es solo académica: es una guía práctica para entender qué tipo de función digestiva se busca mejorar y qué fuentes alimentarias son más apropiadas para cada objetivo.

Lo que la ciencia ha ido revelando en las últimas dos décadas es que la fibra no es simplemente "lo que le da volumen a las heces". Es el sustrato que determina la composición del microbioma, que regula la producción de butirato que nutre el colon, que modula la glucosa y el colesterol postprandial, y que a través de sus metabolitos influye en procesos tan distantes como la inflamación hepática, la regulación del apetito y la función cerebral.

