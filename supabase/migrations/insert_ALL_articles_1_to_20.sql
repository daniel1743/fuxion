### Preguntas frecuentes

**¿Debo retirar el gluten antes de hacerme las pruebas?**
No. Esta es la recomendación más crítica del artículo. Retirar el gluten antes de la serología o la biopsia invalida los resultados. Si ya lo has retirado, comunícaselo al especialista antes de pedir las pruebas para que evalúe la necesidad de una reintroducción controlada.

**¿Es posible que mis síntomas sean de SGNC pero no de celiaquía?**
Sí, y es más frecuente de lo que se cree. El diagnóstico de SGNC se establece por exclusión: primero se descarta la EC con las pruebas adecuadas y luego se observa si los síntomas mejoran con la dieta libre de gluten (o baja en FODMAPs) y reaparecen al reintroducirlo en condiciones controladas.

**¿La avena es segura para los celíacos?**
La avena no contiene gluten en sentido estricto (contiene avenina, una proteína diferente). Sin embargo, la mayoría de la avena comercial está contaminada con gluten durante el procesamiento. La avena certificada "sin gluten" es tolerada por la mayoría de los celíacos, pero un pequeño porcentaje reacciona incluso a la avenina pura. La introducción de avena debe hacerse bajo supervisión médica.

**¿La celiaquía aumenta el riesgo de cáncer?**
El ERGE no controlado aumenta el riesgo de adenocarcinoma esofágico. De forma análoga, la EC no tratada o con dieta sin gluten inadecuada aumenta el riesgo de linfoma de células T asociado a enteropatía (EATL), un linfoma intestinal raro pero severo. El seguimiento clínico regular y el cumplimiento de la dieta reducen significativamente este riesgo.

**¿Cuánto tiempo tarda en recuperarse el intestino tras iniciar la dieta sin gluten?**
La mejoría serológica (descenso de anticuerpos) comienza en semanas. La recuperación histológica completa de las vellosidades puede tardar entre 1 y 5 años dependiendo de la severidad del daño inicial, la edad del paciente y la adherencia estricta a la dieta.

---

### Conclusión

La celiaquía y la sensibilidad al gluten no celíaca representan dos realidades biológicas distintas que comparten un escenario: la intolerancia al gluten como experiencia vivida. Pero sus mecanismos, sus consecuencias y sus manejo difieren de forma radical, y confundirlos tiene costes reales: diagnósticos retrasados, tratamientos inadecuados, complicaciones que se desarrollan en silencio durante años.

La clave para cualquier persona que sospeche un problema con el gluten es la misma: no comenzar la dieta sin gluten antes del diagnóstico. Es el único escenario en el que la ciencia puede dar una respuesta certera. Una vez confirmado el diagnóstico, el tratamiento —una dieta libre de gluten estricta y supervisada— es altamente efectivo para la EC y, en la SGNC, la estrategia más adecuada depende de una evaluación individual que solo puede hacer un especialista.

