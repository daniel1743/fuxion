### Las tres vías de comunicación del eje intestino-cerebro

La comunicación entre el intestino y el cerebro no utiliza un solo canal sino tres simultáneos, que operan con diferentes velocidades y moléculas:

| Vía de Comunicación | Elementos Clave | Velocidad | Dirección Principal |
| :--- | :--- | :--- | :--- |
| **Neural** | Nervio Vago, Sistema Nervioso Entérico | Milisegundos | 80-90% ascendente (intestino → cerebro) |
| **Endocrina** | Serotonina, GLP-1, Grelina, Péptido YY, Cortisol | Minutos a horas | Bidireccional |
| **Inmunológica** | Citoquinas (IL-6, TNF-α, IL-1β), células T reguladoras | Horas a días | Bidireccional |
| **Metabólica** | AGCC (butirato, propionato), triptófano, GABA microbiano | Horas | Ascendente y sistémica |

#### El nervio vago: el cable de fibra óptica transoceánico

El nervio vago es el nervio craneal más largo del cuerpo humano. Se origina en el tronco del encéfalo, desciende por el cuello, atraviesa el tórax y se ramifica hasta llegar al abdomen, donde inerva el esófago, el estómago, el intestino delgado y parte del colon.

Imagínalo como un cable de fibra óptica transoceánico tendido entre dos continentes. La mayoría asumiría que las señales viajan del cerebro (el continente "desarrollado") hacia el intestino (el continente "dependiente"). La realidad es lo opuesto: el 80-90% del tráfico de datos viaja *desde* el intestino *hacia* el cerebro. El intestino es el gran emisor de información; el cerebro, el gran receptor y procesador.

Estas señales ascendentes informan al cerebro sobre el estado del tracto digestivo: qué se está digiriendo, qué microorganismos están presentes, si hay inflamación, si la barrera epitelial está íntegra. El cerebro integra toda esta información y ajusta el comportamiento, el apetito, el estado de ánimo y la respuesta al estrés.

