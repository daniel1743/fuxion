| **Hipoclorhidria** | Elimina la barrera antimicrobiana del pH ácido gástrico | Alta en mayores de 65 años y usuarios crónicos de IBP |
| **Uso crónico de IBP** | Reduce el ácido gástrico, permitiendo el paso de bacterias vivas al intestino | Riesgo aumentado 2-3x según estudio en *Clinical Gastroenterology and Hepatology* |
| **Dismotilidad intestinal** | Reduce la frecuencia e intensidad del CMM | Alta en diabetes, hipotiroidismo, esclerodermia |
| **Cirugías abdominales** | Alteran la anatomía y crean asas ciegas sin barrido | Frecuente en gastrectomías y derivaciones intestinales |
| **Válvula ileocecal disfuncional** | Permite reflujo bacteriano del colon al íleon terminal | Difícil de cuantificar; evaluada mediante imágenes |
| **Inmunosupresión** | Reduce la IgA secretora, un antibiótico natural del intestino | Presente en enfermedades autoinmunes tratadas |

---

### Lo que el SIBO le roba al organismo: malabsorción y deficiencias

Cuando el sobrecrecimiento bacteriano es persistente, el daño supera la incomodidad digestiva. Las bacterias compiten directamente por los nutrientes y alteran procesos de absorción específicos:

- **Vitamina B12:** Las bacterias gramnegativas consumen activamente la cobalamina, llevando a deficiencias que se expresan como neuropatía periférica, fatiga cognitiva y anemia megaloblástica.
- **Grasas y vitaminas liposolubles (A, D, E, K):** La deconjugación prematura de las sales biliares impide la formación de micelas, el vehículo que transporta las grasas hacia el epitelio intestinal. Esto causa esteatorrea y déficits nutricionales acumulados.
- **Hierro:** La inflamación local y la competencia bacteriana contribuyen a la anemia ferropénica sin causa aparente.
- **Carbohidratos:** Fermentados antes de absorberse, generando los síntomas gaseosos característicos pero privando al organismo de su principal fuente de energía.

---

### Diagnóstico: la prueba de aliento y sus limitaciones

El método no invasivo más utilizado para detectar SIBO es la **prueba de aliento** con lactulosa o glucosa. El principio es sencillo: se administra un azúcar al paciente y se mide, durante 2-3 horas, el hidrógeno y/o metano exhalado. Un pico elevado en los primeros 90 minutos sugiere fermentación bacteriana prematura en el intestino delgado.

Sin embargo, esta prueba tiene limitaciones importantes que el lector debe conocer:
- La lactulosa puede producir falsos positivos por variaciones del tránsito intestinal.
- La prueba no detecta el sulfuro de hidrógeno a menos que se utilice un analizador específico.
- La preparación del paciente (dieta baja en fermentables 24 horas antes, ayuno de 12 horas) afecta directamente la validez del resultado.

El estándar de oro sería la aspiración y cultivo del contenido del yeyuno mediante endoscopia, pero su invasividad lo reserva para casos complejos o de investigación clínica.

---

### Intervenciones: lo que la evidencia respalda

> **Nota importante:** Las siguientes intervenciones son de carácter informativo y divulgativo. Ninguna debe aplicarse sin supervisión de un profesional de salud cualificado que haya realizado una evaluación individual.

El abordaje del SIBO en la práctica clínica sigue un orden lógico:

1. **Identificar y tratar la causa subyacente:** Sin resolver el factor precipitante (hipoclorhidria, dismotilidad, válvula disfuncional), cualquier tratamiento será temporal. Esta es la omisión más común en los abordajes no supervisados.

2. **Reducción del sobrecrecimiento:** Bajo prescripción médica, la rifaximina —un antibiótico de acción local con mínima absorción sistémica— es el tratamiento de primera línea con mayor evidencia en SIBO por hidrógeno. En SIBO por metano, la combinación con neomicina ha demostrado mayor eficacia en estudios controlados.

3. **Apoyo a la motilidad:** Ciertos procinéticos, bajo prescripción, buscan restaurar la actividad del CMM. En investigación, el uso de suplementos de motilina como el extracto de jengibre o el ibérico ha mostrado resultados preliminares prometedores.

4. **Estrategias dietéticas de soporte:** La dieta Elemental (nutrientes en forma predigerida) favorece la reducción del sustrato disponible para las bacterias. La dieta baja en FODMAPs apoya el control sintomático sin constituir tratamiento curador.

---

### Desmitificación Científica

**Mito 1:** "Eliminar los carbohidratos cura el SIBO."
**Realidad:** Las dietas bajas en carbohidratos y fermentables (como la dieta SIBO-Specific o baja en FODMAPs) pueden reducir significativamente los síntomas, pero no eliminan el sobrecrecimiento ni abordan el factor causal. Son herramientas de control sintomático, no tratamientos curativos, y su mantenimiento a largo plazo puede reducir la diversidad del microbioma colónico.

**Mito 2:** "Los probióticos son siempre beneficiosos en el SIBO."
**Realidad:** Es un tema genuinamente debatido en la literatura. Añadir más microorganismos durante la fase activa de sobrecrecimiento puede, en algunos pacientes, exacerbar los síntomas al aumentar la masa bacteriana fermentativa en el intestino delgado. La evidencia actual no soporta el uso generalizado de probióticos como primera línea en SIBO activo sin diagnóstico diferencial.

**Mito 3:** "Si no hay diarrea, no puede ser SIBO."
**Realidad:** El SIBO por metano se presenta frecuentemente con estreñimiento severo, no con diarrea. Muchos pacientes con este subtipo han sido diagnosticados erróneamente durante años como estreñimiento funcional o intestino perezoso.

---

### ¿Cuándo consultar a un profesional de la salud?

Busque evaluación médica especializada en gastroenterología si presenta:

- Deficiencia clínica de vitamina B12 sin causa aparente por dieta (vegetarianos/veganos deben tener precaución especial).
- Esteatorrea persistente: heces grasosas, de color pálido, flotantes y con olor intenso.
- Pérdida de peso involuntaria superior al 5% del peso corporal en 3 meses.
- Distensión abdominal tan severa que dificulta la respiración o genera presión torácica.
- Síntomas neurológicos (hormigueo, pérdida de equilibrio) acompañados de síntomas digestivos.
- Historia de cirugía abdominal mayor o uso crónico de inhibidores de bomba de protones (IBP) sin supervisión.

