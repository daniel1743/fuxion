### La nueva nomenclatura: de HGNA a MASLD

En 2023, una comisión internacional de expertos hepatólogos propuso renombrar la condición para reflejar mejor su naturaleza metabólica y eliminar el estigma del término "no alcohólico" (que define la enfermedad por lo que *no* es en lugar de por lo que *es*):

- **MASLD** (Metabolic Dysfunction-Associated Steatotic Liver Disease): reemplaza al término HGNA y requiere la presencia de al menos un criterio de disfunción metabólica (obesidad visceral, hiperglucemia, hipertensión, dislipidemia o resistencia a la insulina).
- **MASH** (Metabolic dysfunction-Associated SteatoHepatitis): reemplaza al término EHNA (esteatohepatitis no alcohólica), la forma inflamatoria y más agresiva de la enfermedad.

En este artículo usamos ambos términos indistintamente para facilitar la búsqueda e identificación por parte del lector.

