### Desmitificación Científica

**Mito 1:** "Consumir alimentos ricos en serotonina (como el plátano) eleva la serotonina en el cerebro."
**Realidad:** La serotonina no cruza la barrera hematoencefálica. Comer plátano no aumenta la serotonina cerebral. Lo que sí puede hacerlo es consumir alimentos ricos en triptófano (como el pavo, huevos, semillas de calabaza) combinados con carbohidratos, ya que el índice glucémico favorece el transporte de triptófano al cerebro.

**Mito 2:** "El estrés emocional no tiene efectos físicos reales en el intestino."
**Realidad:** Los efectos son completamente reales y medibles: el estrés agudo y crónico altera la motilidad intestinal, reduce la diversidad de la microbiota, aumenta la permeabilidad intestinal y eleva los marcadores inflamatorios séricos. La psiconeuroinmunología es la disciplina que estudia estos mecanismos con rigor científico creciente.

**Mito 3:** "Los problemas intestinales son siempre la causa de la depresión, o viceversa."
**Realidad:** La relación es bidireccional y circular: la disbiosis puede contribuir a síntomas depresivos, y la depresión puede agravar la disbiosis. Ninguno de los dos es siempre "la causa" del otro. El abordaje más efectivo reconoce ambas dimensiones simultáneamente.

