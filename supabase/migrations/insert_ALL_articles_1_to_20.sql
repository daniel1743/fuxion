### La enfermedad que existe sin "verse" en los análisis

Pocas experiencias médicas son tan frustrantes como esta: te despiertas con dolor abdominal, vas al baño cuatro veces antes de llegar al trabajo, llevas meses sin poder comer tranquilamente en un restaurante, y cuando por fin vas al médico, la colonoscopia sale perfecta, los análisis de sangre están dentro del rango normal y la ecografía no muestra nada. El médico te dice "es funcional" y tú te preguntas si todo está en tu cabeza.

No lo está.

El Síndrome del Intestino Irritable es una condición con mecanismos fisiopatológicos reales, medibles y creciente­mente bien documentados. No es una enfermedad psicosomática, aunque el estrés la agrave. No es una debilidad de carácter. No es algo que se "controla con la mente". Es un desorden neurogastroenterológico complejo en el que el sistema nervioso entérico, la microbiota, la barrera intestinal y el cerebro están funcionando de forma desregulada simultáneamente.

