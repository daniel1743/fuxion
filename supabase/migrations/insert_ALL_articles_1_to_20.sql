- **Mito:** Un test de aliento positivo confirma que se tiene intolerancia genética.
- **Realidad:** El test de aliento con lactosa (medición de hidrógeno espirado) detecta la fermentación bacteriana de la lactosa no absorbida, pero no distingue entre causa primaria y secundaria. Un resultado positivo debe interpretarse en el contexto clínico completo.

