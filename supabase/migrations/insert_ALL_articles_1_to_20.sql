### ¿Cuándo consultar a un profesional de la salud?

Busque atención médica inmediata o urgente si presenta:

- **Disfagia progresiva:** Dificultad para tragar que empeora con el tiempo o que afecta tanto a sólidos como a líquidos.
- **Odinofagia:** Dolor agudo al tragar, que puede indicar esofagitis severa o úlcera esofágica.
- **Hematemesis:** Vómitos con sangre o material de aspecto similar a posos de café.
- **Melenas:** Heces negras, brillantes y malolientes, sugestivas de sangrado digestivo alto.
- **Pérdida de peso involuntaria** junto a síntomas de reflujo o disfagia.
- **Síntomas nocturnos severos** que interrumpen el sueño de forma crónica.
- **Síntomas que no mejoran** tras 4-8 semanas de tratamiento médico supervisado.

