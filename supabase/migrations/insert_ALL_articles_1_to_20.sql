### Criterios diagnósticos: ¿cómo se diagnostica el SII?

El SII se diagnostica mediante los **Criterios de Roma IV** (2016), el estándar internacional vigente. Para que el diagnóstico sea aplicable:

> **Dolor abdominal recurrente** al menos **1 día por semana** durante los últimos **3 meses**, con inicio hace más de **6 meses**, asociado a dos o más de los siguientes criterios:
> * Relacionado con la defecación (mejora o empeora al defecar)
> * Asociado a cambio en la frecuencia de las deposiciones
> * Asociado a cambio en la forma o apariencia de las heces

El diagnóstico de SII es de exclusión en la práctica clínica: requiere descartar causas orgánicas (Enfermedad Inflamatoria Intestinal, celiaquía, infección, cáncer) antes de establecerse con certeza.

