> **Lo más importante**
> * La permeabilidad intestinal describe la capacidad de la barrera del intestino para permitir el paso selectivo de agua y nutrientes mientras limita el ingreso de microorganismos y moléculas potencialmente dañinas.
> * Un aumento de esta permeabilidad puede producirse cuando se alteran las uniones estrechas (tight junctions) entre las células intestinales.
