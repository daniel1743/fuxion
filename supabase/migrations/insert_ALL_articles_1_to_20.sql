### ¿Cuándo consultar a un profesional de la salud?

Es crítico descartar enfermedades orgánicas graves antes de asumir que los síntomas son funcionales. Busque evaluación médica urgente si presenta:

- Sangre visible en las heces o sangrado rectal de cualquier color.
- Inicio de síntomas digestivos severos después de los 50 años (sin diagnóstico previo).
- Despertar nocturno recurrente por dolor abdominal o urgencia defecatoria (el SII no suele despertar por la noche).
- Pérdida de peso involuntaria significativa.
- Fiebre persistente o marcadores inflamatorios elevados (calprotectina fecal alta, PCR elevada).
- Historia familiar de Enfermedad de Crohn, Colitis Ulcerosa o cáncer colorrectal.
- Aparición de síntomas en el contexto de viajes recientes a zonas con riesgo de infección entérica.
- Anemia ferropénica o déficit de vitamina B12 inexplicado.

