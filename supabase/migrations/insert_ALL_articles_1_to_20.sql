### Las mariposas en el estómago son neurociencia, no poesía

Existe una experiencia que prácticamente todos los seres humanos reconocen: ese nudo en el estómago antes de una presentación importante, el impulso repentino de ir al baño antes de un examen, la náusea física ante una noticia devastadora. Durante siglos, estas reacciones se atribuyeron a la mente "afectando" al cuerpo de manera metafórica.

La neurociencia de las últimas dos décadas ha transformado completamente esta comprensión.

El intestino no simplemente recibe órdenes del cerebro. Escucha, procesa y responde. Envía señales. Modifica el estado emocional. Regula la producción de sustancias que afectan la cognición. Y cuando el ecosistema microbiano del intestino se altera, el cerebro lo siente: en el humor, en la ansiedad, en la calidad del sueño, en la capacidad de gestionar el estrés.

Esto no es medicina alternativa ni especulación: es el resultado de más de 15.000 publicaciones científicas en los últimos 20 años que han desentrañado, capa por capa, la extraordinaria complejidad de lo que los investigadores denominan el **eje microbiota-intestino-cerebro**.

