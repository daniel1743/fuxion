### ¿Cuándo consultar a un profesional de la salud?

Busque evaluación médica o psiquiátrica especializada si presenta:

- Ansiedad o depresión severa que incapacita su rutina diaria o laboral, independientemente de su causa aparente.
- Síntomas digestivos crónicos (diarrea, estreñimiento, dolor abdominal) que coinciden temporalmente con episodios de estrés o cambios de humor significativos.
- Cambios neurológicos bruscos: confusión, pérdida del habla, alteraciones del equilibrio o la coordinación.
- Disfagia (dificultad para tragar) de aparición súbita o progresiva.
- Pérdida de peso involuntaria junto a síntomas neurológicos o digestivos.
- Pensamientos de autolesión o ideación suicida: busque atención urgente de salud mental de inmediato.

