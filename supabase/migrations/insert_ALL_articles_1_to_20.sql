### Preguntas frecuentes

**¿La disbiosis causa directamente enfermedades como la depresión o la obesidad?**
La investigación establece asociaciones estadísticas fuertes, no causalidad probada. Es probable que la relación sea bidireccional: la disbiosis puede contribuir a estas condiciones, y estas condiciones pueden a su vez agravar la disbiosis. La dirección de la causalidad es aún objeto de estudio activo.

**¿Cómo se recupera el microbioma tras un ciclo de antibióticos?**
La recuperación es parcial y variable. Algunos estudios muestran que el microbioma puede tardar entre 6 y 12 meses en acercarse a su composición previa, y en algunos individuos ciertos grupos no se recuperan completamente. Aumentar la ingesta de fibra prebiótica y alimentos fermentados durante y después del tratamiento apoya la recuperación.

**¿Qué es el trasplante de microbiota fecal (TMF) y para qué se usa?**
El TMF consiste en transferir heces de un donante sano a un receptor con una microbiota alterada. Actualmente es el único tratamiento con eficacia probada para la infección recurrente por *Clostridium difficile* (tasas de éxito superiores al 80-90%). Para otras condiciones como la obesidad o el autismo, la evidencia es aún preliminar e insuficiente para recomendarlo fuera de contextos de investigación clínica.

**¿Existe alguna prueba que pueda hacerse en una consulta médica normal?**
La calprotectina fecal es una prueba accesible que mide inflamación del colon. No diagnostica disbiosis pero orienta sobre si hay inflamación orgánica que merece investigarse. La evaluación clínica exhaustiva (historia dietética, síntomas, hábitos intestinales) sigue siendo el punto de partida más valioso en la consulta médica.

**¿Los niños también pueden tener disbiosis?**
Sí, y los primeros 1.000 días de vida (desde la concepción hasta los 2 años) son el período más crítico para la programación del microbioma. El tipo de parto, la lactancia materna, la introducción alimentaria y el uso de antibióticos en esta etapa tienen efectos a largo plazo sobre la composición microbiana y el riesgo de enfermedades alérgicas, autoinmunes y metabólicas.

---

### Conclusión

El microbioma intestinal es, en todos los sentidos del término, un órgano. No un accesorio, no un acompañante, sino un sistema funcional con roles metabólicos, inmunológicos y neurológicos tan relevantes como cualquier otro órgano del cuerpo humano. La disbiosis —su desequilibrio— no es simplemente "tener malas bacterias": es la ruptura de un ecosistema complejo que mantiene en equilibrio funciones que van desde la absorción de minerales hasta la regulación del estado de ánimo.

Comprender la disbiosis como un mecanismo —no como una etiqueta diagnóstica— es el primer paso para abordarla de forma racional. No con un suplemento milagroso, sino con la misma paciencia y consistencia con la que se construye cualquier ecosistema saludable: diversidad alimentaria, reducción de agresores conocidos, gestión del estrés y, cuando el cuadro clínico lo justifica, evaluación médica especializada.

