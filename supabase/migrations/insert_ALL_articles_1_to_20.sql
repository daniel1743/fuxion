### Preguntas frecuentes

**¿El intestino realmente influye en la depresión?**
La evidencia epidemiológica muestra consistentemente mayor prevalencia de síntomas depresivos en personas con enfermedades inflamatorias intestinales y viceversa. Los mecanismos propuestos incluyen la desviación del triptófano hacia la vía kinurenina, la neuroinflamación mediada por LPS y la alteración de la señalización serotoninérgica. Sin embargo, la relación causal directa en humanos sigue siendo objeto de investigación activa.

**¿Qué son los psicobióticos y están disponibles?**
Son cepas probióticas específicas estudiadas por sus efectos sobre la salud mental. Algunas ya están disponibles como suplementos (*L. rhamnosus* JB-1, *B. longum* 1714), pero su uso en contextos clínicos de salud mental sigue siendo investigacional. Consulte con un profesional antes de iniciar su uso en presencia de trastornos mentales diagnosticados.

**¿Puede la dieta mejorar la ansiedad a través del eje intestino-cerebro?**
La investigación sugiere que sí. Dietas con alta diversidad de fibra prebiótica, alimentos fermentados y baja carga glucémica se asocian con mejor función del eje intestino-cerebro. Sin embargo, la dieta no reemplaza el tratamiento psicoterapéutico o farmacológico cuando este está indicado.

**¿El nervio vago se puede "entrenar"?**
