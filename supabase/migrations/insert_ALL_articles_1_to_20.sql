### Fisiopatología: los cuatro mecanismos del ERGE

El ERGE no tiene una causa única. La literatura científica identifica al menos cuatro mecanismos principales que pueden operar de forma independiente o combinada:

| Mecanismo | Descripción Fisiopatológica | Factores Asociados |
| :--- | :--- | :--- |
| **Relajaciones transitorias del EEI** | El esfínter se relaja en momentos inapropiados, fuera de la deglución. | Distensión gástrica, alcohol, tabaco, cafeína, menta |
| **Hipotensión crónica del EEI** | Tono basal reducido de forma persistente. | Hernia de hiato, esclerodermia, ciertos medicamentos |
| **Presión intraabdominal elevada** | Fuerza mecánica que empuja el contenido gástrico hacia arriba. | Obesidad visceral, embarazo, ascitis, ropa compresiva |
| **Hipoclorhidria** | Señal ácida insuficiente para mantener el tono del EEI. | Edad avanzada, infección por *H. pylori*, uso de IBP |

### La paradoja de la hipoclorhidria

Este es quizás el punto más contraintuitivo —y más importante— del artículo. La hipoclorhidria (ácido gástrico bajo) produce síntomas casi idénticos al exceso de ácido: ardor, regurgitación, sensación de pesadez postprandial. Sin embargo, el mecanismo es opuesto.

Cuando los niveles de ácido son insuficientes:
1. La señal para cerrar el EEI es débil → el reflujo ocurre.
2. La digestión proteica es ineficiente → el vaciado gástrico se enlentece.
3. El estómago permanece lleno más tiempo → aumenta la presión intraabdominal.
4. Las bacterias no son destruidas por el ácido → aumenta el riesgo de SIBO.

Tratar la hipoclorhidria con más antiácidos (como hace un paciente que automédica su ardor) agrava cada uno de estos cuatro puntos. Esta es la razón por la que algunos pacientes notan que su reflujo empeora progresivamente con el uso crónico de IBP sin supervisión médica.

