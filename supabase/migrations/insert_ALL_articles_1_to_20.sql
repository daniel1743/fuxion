### ¿Qué es la fibra dietética a nivel bioquímico?

La fibra dietética es el conjunto de polisacáridos de origen vegetal (y algunos oligosacáridos y ligninas) que resisten la digestión por las enzimas del intestino delgado humano y llegan intactos al colon, donde son fermentados parcial o totalmente por la microbiota.

Esta resistencia a la digestión no es un defecto del sistema: es una característica de la estructura química de estas moléculas. Los enlaces beta-glucosídicos de la celulosa, por ejemplo, son resistentes a las amilasas humanas, que están diseñadas para romper enlaces alfa. El resultado es que la fibra transita por el intestino delgado sin ser absorbida y llega al colon en gran parte intacta, donde los miles de millones de bacterias que habitan ese tramo sí tienen las enzimas necesarias para fermentarla.

