### Fisiopatología: la ciudad interior que colapsa

Imagina el microbioma intestinal como una metrópolis de varios millones de habitantes, con barrios especializados, infraestructura de transporte y servicios públicos esenciales.

Las bacterias beneficiosas —*Faecalibacterium prausnitzii*, *Akkermansia muciniphila*, los *Lactobacillus* y *Bifidobacterium*— son los servicios públicos de la ciudad: limpian las calles, mantienen la infraestructura de los edificios (la capa de moco intestinal), producen la electricidad que alimenta el barrio (el butirato que nutre los colonocitos) y patrullan los accesos para que no entren elementos peligrosos.

Cuando hay disbiosis, es como si un apagón dejara la ciudad sin servicios básicos. Los barrios se deterioran, la infraestructura se rompe y grupos oportunistas aprovechan el caos para expandirse. En términos biológicos, esto se traduce en:

- **Reducción del butirato:** El butirato es el ácido graso de cadena corta preferido por las células del colon (colonocitos). Sin él, las células se debilitan, la capa de moco se adelgaza y la barrera epitelial pierde integridad.
- **Aumento de LPS:** Las bacterias gramnegativas oportunistas liberan lipopolisacáridos (LPS) al fragmentarse. El LPS es una endotoxina potente que activa receptores TLR4 del sistema inmune, desencadenando la producción de citoquinas proinflamatorias como el TNF-α, la IL-6 y la IL-1β.
- **Endotoxemia metabólica:** Cuando las LPS atraviesan una barrera intestinal ya debilitada, ingresan al torrente sanguíneo y mantienen un estado de inflamación crónica de bajo grado. Este mecanismo se ha propuesto como nexo entre la disbiosis y condiciones como la resistencia a la insulina, la obesidad y la depresión.

