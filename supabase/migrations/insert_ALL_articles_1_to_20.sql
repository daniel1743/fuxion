Cuando el hígado recibe de forma crónica más sustancias de las que puede procesar —ya sea porque la dieta aporta excesivas calorías, porque hay resistencia a la insulina que dispara la producción de grasa interna, o porque el intestino envía un flujo constante de endotoxinas proinflamatorias— sus células comienzan a acumular triglicéridos en su interior. Este es el origen del hígado graso no alcohólico.

