Ambos términos se utilizan a menudo de forma intercambiable en la literatura científica. La "intolerancia a la histamina" es un término más amplio que describe la aparición de síntomas tras la ingesta de histamina, mientras que la "histaminosis entérica" enfatiza el origen intestinal del desequilibrio.

