### Preguntas frecuentes

**¿Por qué el exceso de fibra causa gases?**
Al fermentar la fibra, las bacterias colónicas producen hidrógeno, dióxido de carbono y, en algunas personas, metano. Cuando la cantidad de fibra supera la capacidad de adaptación de la microbiota, o cuando se introduce una nueva fuente fermentable de forma brusca, la producción de gas excede la capacidad de absorción y expulsión del intestino, generando distensión. La solución es gradual, no la eliminación de la fibra.

**¿Cuánta fibra debo consumir diariamente?**
Las recomendaciones institucionales varían ligeramente: la OMS sugiere mínimo 25g; la Academia de Nutrición y Dietética de EE.UU. recomienda 25g para mujeres y 38g para hombres adultos. Un objetivo práctico es entre 25 y 35g diarios de fuentes variadas, priorizando alimentos integrales sobre suplementos aislados.

**¿El almidón resistente del arroz y la papa enfriada realmente funciona?**
Sí. El proceso de retrogradación —el enfriamiento del almidón cocido a 4°C durante al menos 12-24 horas— reconfigura la estructura cristalina del almidón, haciéndolo resistente a las amilasas. Recalentar posteriormente lo destruye parcialmente, pero no del todo. El arroz o la papa cocida y enfriada (y consumida fría o recalentada brevemente) tiene un índice glucémico menor y más almidón resistente que recién cocida.

**¿Los niños necesitan la misma cantidad de fibra que los adultos?**
No. Las recomendaciones para niños son menores y varían por edad. Una guía práctica es "edad + 5 gramos" para niños de 3 a 8 años (un niño de 6 años necesita ~11g). A partir de los 14-18 años se aproximan a los valores adultos. La fibra en la infancia es especialmente importante para la programación del microbioma y la prevención de estreñimiento funcional.

**¿La fibra puede ayudar a controlar el peso?**
La evidencia es moderadamente favorable. La fibra soluble aumenta la saciedad (a través del enlentecimiento del vaciado gástrico y la señalización de hormonas como el péptido YY y el GLP-1), mientras que la fermentación produce propionato, que reduce la señalización del apetito a nivel central. Sin embargo, la fibra sola no es un tratamiento para la obesidad: funciona como parte de un patrón dietético global saludable.

