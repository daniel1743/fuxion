### Fisiopatología: cinco mecanismos que se retroalimentan

El SII no tiene una causa única. Es el resultado de la interacción de al menos cinco mecanismos que se potencian mutuamente:

#### 1. Hipersensibilidad visceral: los sensores están demasiado sensibles

Las personas con SII tienen una percepción alterada del dolor intestinal. Los mecanorreceptores y nociceptores del intestino responden con mayor intensidad a estímulos que en personas sin SII serían completamente inocuos: el paso de gas, la distensión normal postprandial o el tránsito habitual de heces generan señales de dolor que el sistema nervioso central interpreta como amenazantes.

Imagina que el sistema de alarma de tu casa tiene el umbral de sensibilidad ajustado al máximo: la apertura de una ventana activa la misma alarma que una intrusión real. En el SII, las células nerviosas del intestino (que expresan mayor número de receptores de serotonina y sustancia P) disparan señales de dolor ante estímulos que no justifican esa respuesta.

#### 2. Alteraciones en la motilidad intestinal

El sistema nervioso entérico coordina las contracciones peristálticas del intestino. En el SII, este sistema envía señales erráticas que se traducen en dos patrones extremos:
- **Tránsito acelerado** (SII-D): las contracciones son más frecuentes e intensas, el agua no se reabsorbe completamente, y las heces llegan al recto antes de estar formadas.
- **Tránsito enlentecido** (SII-E): las contracciones son débiles e infrecuentes, las heces permanecen demasiado tiempo en el colon, pierden agua y se endurecen.

#### 3. Alteraciones del microbioma y disbiosis post-infecciosa

Hasta el 25-30% de los casos de SII aparecen después de una gastroenteritis aguda ("SII post-infeccioso"). La infección altera la composición microbiana, aumenta la permeabilidad intestinal y puede sensibilizar de forma duradera los nervios entéricos. Incluso en casos sin episodio infeccioso previo, los pacientes con SII muestran menor diversidad microbiana y menor abundancia de *Bifidobacterium* y *Lactobacillus* respecto a controles sanos.

#### 4. Permeabilidad intestinal aumentada

Estudios con medición de zonulina y lactulosol-manitol muestran que una proporción significativa de pacientes con SII tiene aumento de la permeabilidad intestinal, especialmente en el subtipo SII-D. Esta mayor permeabilidad permite el paso de antígenos bacterianos a la lámina propia, activando células inmunes y manteniendo un estado de microinflamación que sensibiliza los nervios entéricos locales.

#### 5. Eje intestino-cerebro desregulado

El estrés crónico activa el eje hipotálamo-hipófisis-adrenal (HHA), eleva el cortisol y la hormona liberadora de corticotropina (CRH), que tiene receptores directos en el intestino y acelera el tránsito. Este mecanismo explica por qué el estrés emocional agudo desencadena episodios diarreicos en muchos pacientes, y por qué las intervenciones psicoterapéuticas (TCC, hipnoterapia dirigida al intestino) tienen eficacia documentada en el SII.

