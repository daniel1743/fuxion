### Intervenciones: de la evidencia al manejo individual

> **Nota importante:** Las estrategias mencionadas a continuación son de carácter informativo. El manejo del ERGE debe ser supervisado por un médico que pueda evaluar si el reflujo es ácido o no ácido, la competencia del EEI y la presencia de complicaciones como el esófago de Barrett.

**Cambios conductuales con respaldo clínico:**
- Elevar la cabecera de la cama 15-20 cm favorece el aclaramiento esofágico nocturno y reduce la exposición ácida en el esófago durante el sueño.
- Evitar acostarse en las 3 horas posteriores a la última comida elimina la presión sobre el EEI cuando la distensión gástrica es máxima.
- La pérdida de peso en pacientes con sobrepeso u obesidad visceral reduce de forma significativa la presión intraabdominal y mejora los síntomas.

**Sobre los medicamentos:**
Los IBP (omeprazol, lansoprazol, pantoprazol) son fármacos eficaces para reducir el ácido gástrico y mejorar los síntomas del ERGE ácido. Sin embargo, su uso crónico sin supervisión médica y sin reevaluación periódica se asocia en la literatura a:
- Mayor riesgo de infecciones entéricas (incluyendo *C. difficile*).
- Disminución de la absorción de vitamina B12, hierro, calcio y magnesio.
- Alteraciones en la microbiota intestinal y mayor riesgo de SIBO.
- Posible riesgo de enfermedad renal crónica en uso muy prolongado (evidencia observacional, en revisión).

