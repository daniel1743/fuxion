### Un escudo que se renueva cada hora

El estómago humano produce entre 1,5 y 3 litros de jugo gástrico al día. Ese jugo contiene ácido clorhídrico con un pH tan bajo que podría disolver metales, y una enzima llamada pepsina capaz de fragmentar proteínas complejas. Si esa misma mezcla entrara en contacto con la piel, causaría una quemadura química inmediata. Sin embargo, el estómago permanece intacto. ¿Cómo es posible? La respuesta está en una capa de moco que, aunque parece frágil, constituye una de las barreras biológicas más sofisticadas del organismo.

### ¿Qué es exactamente el moco gástrico?

El moco gástrico no es una sustancia homogénea ni estática. Se trata de un gel viscoelástico, secretado de forma continua por las células mucosas del cuello gástrico y las células foveolares. Su composición incluye:

- **Mucinas (MUC5AC y MUC6):** Glicoproteínas de alto peso molecular que forman una red tridimensional capaz de retener agua.
- **Bicarbonato (HCO₃⁻):** Ión alcalino secretado por las células epiteliales superficiales.
- **Lípidos y fosfolípidos:** Contribuyen a la hidrofobicidad de la capa, repeliendo sustancias hidrosolubles agresivas.
- **Inmunoglobulinas (IgA secretora):** Primera línea de defensa inmunológica frente a patógenos.

Esta mezcla se organiza en dos capas funcionalmente distintas:

| Capa | Grosor aproximado | pH | Función principal |
| :--- | :--- | :--- | :--- |
| **Capa insoluble (externa)** | 50-200 µm | Ácido (pH 1-2) | Atrapa bacterias y partículas; se mezcla con el contenido luminal. |
| **Capa soluble (interna)** | 50-100 µm | Neutro-alcalino (pH 6-7) | Mantiene un microambiente protector sobre las células epiteliales. |

### La analogía del arrecife de coral

Imagina un arrecife de coral en medio de un océano agitado. La parte externa del arrecife recibe el impacto constante de las olas, pero en su interior, en las grietas y cuevas, el agua permanece tranquila y templada. El moco gástrico funciona de manera similar: la capa externa está en contacto directo con el ácido y las enzimas, mientras que la capa interna, gracias al bicarbonato secretado por las células, mantiene un pH casi neutro. Ese gradiente de pH —desde 1-2 en la luz hasta 6-7 en la superficie celular— es la clave de la protección.

### Mecanismos de defensa integrados

La barrera mucosa no actúa sola. Forma parte de un sistema de defensa multicapa que incluye:

| Componente | Mecanismo de acción | Consecuencia de su fallo |
| :--- | :--- | :--- |
| **Capa de moco + bicarbonato** | Neutraliza el ácido antes de que llegue a las células. | Erosión directa del epitelio por ácido y pepsina. |
| **Uniones estrechas entre células epiteliales** | Impiden el paso paracelular de ácido y enzimas. | Edema, inflamación y necrosis celular. |
| **Flujo sanguíneo submucoso** | Aporta oxígeno, nutrientes y bicarbonato; elimina toxinas. | Isquemia local, favoreciendo la formación de úlceras. |
| **Prostaglandinas (PGE₂, PGI₂)** | Estimulan la secreción de moco y bicarbonato; inhiben la secreción ácida. | Reducción de la producción de moco y aumento de la vulnerabilidad. |
| **Factor de crecimiento epidérmico (EGF)** | Promueve la reparación y regeneración celular. | Retraso en la cicatrización de lesiones mucosas. |

### Factores que comprometen la barrera mucosa

Diversos agentes externos e internos pueden debilitar esta barrera protectora:

- **AINEs (antiinflamatorios no esteroideos):** Inhiben la ciclooxigenasa-1 (COX-1), reduciendo la síntesis de prostaglandinas protectoras. Esto disminuye la producción de moco y bicarbonato, y aumenta la susceptibilidad a úlceras.
- **Infección por *Helicobacter pylori*:** Esta bacteria produce ureasa, que genera amoníaco y neutraliza localmente el ácido, pero también secreta toxinas (CagA, VacA) que dañan directamente las células epiteliales y alteran la producción de mucinas.
- **Estrés fisiológico severo:** Quemaduras extensas, traumatismos o sepsis pueden reducir el flujo sanguíneo gástrico, comprometiendo la entrega de bicarbonato y oxígeno.
- **Consumo crónico de alcohol:** El etanol altera la estructura de las mucinas y aumenta la permeabilidad de la capa de moco.
- **Reflujo biliar:** Las sales biliares, al alcanzar el estómago, desestabilizan la capa lipídica del moco.

### Desmitificación Científica

- **Mito:** Beber leche "recubre" el estómago y protege contra la acidez.
- **Realidad:** La leche tiene un efecto amortiguador temporal, pero también estimula la secreción de gastrina, lo que a largo plazo puede aumentar la producción de ácido. No sustituye los mecanismos fisiológicos de protección.

- **Mito:** El moco gástrico es una capa estática que se desgasta con la edad.
- **Realidad:** El moco se renueva constantemente (cada 1-2 horas) mediante secreción continua. Aunque la calidad puede disminuir con la edad o ciertas enfermedades, no es un "desgaste" irreversible.

- **Mito:** Los antiácidos de venta libre fortalecen la barrera mucosa.
- **Realidad:** Los antiácidos neutralizan el ácido ya secretado, pero no estimulan la producción de moco ni bicarbonato. Su uso prolongado sin supervisión médica puede enmascarar problemas subyacentes.

