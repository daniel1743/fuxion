- Coloración amarillenta en la piel, el blanco de los ojos (ictericia) o la orina oscura (color té).
- Distensión abdominal progresiva con sensación de pesadez o líquido (posible ascitis).
- Aparición de pequeños vasos sanguíneos en forma de araña (angiomas en araña) en el tórax o la espalda.
