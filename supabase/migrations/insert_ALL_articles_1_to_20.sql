### Fisiopatología: el almacén que se convierte en zona de conflicto

#### Primera etapa — La acumulación (esteatosis simple)

Imagina el hepatocito (la célula hepática) como un empleado muy eficiente de un almacén de distribución. Recibe paquetes (nutrientes), los procesa y los despacha hacia sus destinos finales. El problema comienza cuando llegan demasiados paquetes de grasa al mismo tiempo y no hay capacidad de procesarlos y distribuirlos tan rápido como llegan.

Los paquetes sin procesar —triglicéridos y ácidos grasos— se almacenan temporalmente dentro de la célula en forma de gotas lipídicas. Cuando la grasa acumulada supera el 5% del peso total del hígado, se habla de esteatosis. Esta primera etapa es potencialmente reversible con cambios dietéticos y de actividad física.

**Las tres fuentes principales de grasa hepática:**
1. **Lipogénesis de novo** (~26%): El hígado convierte el exceso de carbohidratos simples (especialmente fructosa) en ácidos grasos. La fructosa es especialmente problemática porque, a diferencia de la glucosa, se metaboliza casi exclusivamente en el hígado y puede desbordarlo rápidamente.
2. **Lipólisis periférica aumentada** (~59%): El tejido adiposo resistente a la insulina libera ácidos grasos libres al torrente sanguíneo de forma descontrolada, y estos llegan al hígado vía la vena porta.
3. **Grasa dietética directa** (~15%): Una proporción menor proviene directamente de la dieta.

#### Segunda etapa — La inflamación (esteatohepatitis, MASH/EHNA)

Cuando los hepatocitos acumulan demasiada grasa, su función normal se deteriora. Se produce estrés oxidativo: las mitocondrias sobreexigidas generan más especies reactivas de oxígeno (ROS) de las que los sistemas antioxidantes del hígado pueden neutralizar. Este exceso de ROS daña el ADN mitocondrial, las membranas celulares y las proteínas del hepatocito.

El daño celular activa señales de inflamación que reclutan células del sistema inmune (células de Kupffer, neutrófilos, células T). Esta respuesta inflamatoria, inicialmente protectora, se vuelve destructiva cuando es crónica. El resultado es el balonamiento de los hepatocitos y la aparición de inflamación activa en la biopsia: esteatohepatitis.

#### Tercera etapa — La cicatriz irreversible (fibrosis y cirrosis)

La inflamación crónica activa las células estrelladas hepáticas, que en condiciones normales están quiescentes. Al activarse, producen colágeno de forma descontrolada, sustituyendo el tejido hepático funcional por tejido cicatricial rígido. Este proceso, llamado fibrosis, puede avanzar hasta la cirrosis, donde la arquitectura normal del hígado está tan destruida que el órgano pierde funcionalidad crítica.

