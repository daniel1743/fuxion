### El gluten: anatomía de una proteína compleja

Antes de entrar en los mecanismos de enfermedad, es necesario comprender qué es exactamente el gluten desde el punto de vista bioquímico.

El gluten no es una sola proteína: es una red de proteínas de almacenamiento presentes en el endospermo de tres cereales —trigo, cebada y centeno— que se forma cuando las gluteninas y las gliadinas se hidratan y se entrelazan. Es esta red la que da al pan su elasticidad y esponjosidad características.

La fracción más relevante desde el punto de vista inmunológico es la **gliadina**, especialmente la alfa-gliadina. Sus secuencias de aminoácidos son particularmente resistentes a la degradación por las enzimas digestivas humanas, lo que significa que fragmentos de gliadina parcialmente digerida (péptidos) llegan intactos al intestino delgado, donde el sistema inmune del individuo susceptible los detecta y reacciona.

---

### Enfermedad Celíaca: cuando el sistema inmune se ataca a sí mismo

La Enfermedad Celíaca afecta aproximadamente al 1% de la población mundial, aunque se estima que hasta el 80% de los casos no han sido diagnosticados. No es una intolerancia alimentaria ni una alergia: es una enfermedad autoinmune con base genética, desencadenada por un factor ambiental específico (el gluten).

#### La biología del "fuego amigo" autoinmune

Para que la EC se desarrolle, deben concurrir tres factores:
1. **Predisposición genética:** El 95% de los pacientes celíacos expresan los haplotipos HLA-DQ2 o HLA-DQ8, aunque tener estos genes no garantiza desarrollar la enfermedad.
2. **Exposición al gluten:** El factor ambiental desencadenante.
3. **Ruptura de la tolerancia inmune:** El momento en que el sistema inmune deja de tolerar el gluten y comienza a reaccionar contra él.

Imagina el sistema inmune como un ejército de defensa con reconocimiento facial sofisticado. En la EC, el sistema identifica correctamente al fragmento de gliadina como extraño. Pero comete un error fatal de identificación cruzada: la proteína **transglutaminasa tisular (tTG)** —una enzima propia del organismo que modifica los péptidos de gliadina— es reconocida como parte del enemigo. El ejército inmune dispara contra el gluten y, al mismo tiempo, contra las propias células del intestino que expresan la tTG. Es un "fuego amigo" molecular y meticulosamente destructivo.

El resultado es la atrofia progresiva de las vellosidades intestinales, esas microscópicas proyecciones que multiplican la superficie de absorción del intestino delgado hasta alcanzar el equivalente a una cancha de tenis (aproximadamente 250 m²). Cuando las vellosidades se aplanan, esa superficie de absorción colapsa a una fracción mínima de su capacidad.

#### La escala de Marsh: midiendo el daño

El daño histológico en la EC se clasifica mediante la **Escala de Marsh**, que va del grado 0 (mucosa normal) al grado 3c (atrofia total de las vellosidades con hiperplasia críptica severa). Esta escala, observada mediante biopsia duodenal durante una endoscopia, es un pilar diagnóstico fundamental.

| Grado Marsh | Descripción Histológica | Implicación Clínica |
| :--- | :--- | :--- |
| **0** | Mucosa normal | Sin daño. No es celiaquía activa. |
| **1** | Aumento de linfocitos intraepiteliales (>25/100 enterocitos) | Daño inicial; puede verse en SGNC o infecciones. |
| **2** | Grado 1 + hiperplasia de las criptas | Daño moderado con intentos de regeneración. |
| **3a** | Atrofia parcial de vellosidades | Diagnóstico de EC probable con serología positiva. |
| **3b** | Atrofia subtotal de vellosidades | Daño significativo; malabsorción frecuente. |
| **3c** | Atrofia total de vellosidades | Daño severo; riesgo de complicaciones graves. |

