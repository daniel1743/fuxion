### El almidón resistente: el tercer tipo que cambia las reglas

Existe una tercera categoría que merece atención especial: el **almidón resistente (AR)**. Aunque técnicamente es un carbohidrato, se comporta funcionalmente como una fibra soluble fermentable de alta potencia.

El almidón resistente "resiste" la digestión en el intestino delgado porque su estructura cristalina o su encapsulamiento físico impide el acceso de las amilasas. Cuando llega al colon, es fermentado con especial avidez por bacterias productoras de butirato como *Ruminococcus bromii* y *Faecalibacterium prausnitzii*.

