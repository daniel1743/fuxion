### Una molécula con dos caras

La histamina es una de las moléculas más versátiles y, a la vez, más incomprendidas del cuerpo humano. La mayoría de las personas la asocian exclusivamente con las reacciones alérgicas: estornudos, urticaria, picazón. Sin embargo, esta amina biogénica desempeña funciones esenciales en la regulación de la secreción ácida del estómago, la modulación de la respuesta inmune y la comunicación entre neuronas. El problema no es la histamina en sí misma. El problema aparece cuando los mecanismos que controlan sus niveles se desequilibran, especialmente a nivel intestinal.

### ¿Qué es realmente la histaminosis entérica?

A diferencia de una alergia alimentaria mediada por IgE, donde el sistema inmune reacciona de forma exagerada frente a una proteína específica, la histaminosis entérica se refiere a una acumulación excesiva de histamina en el tracto digestivo. Esta acumulación puede ocurrir por dos vías principales: un aporte excesivo desde la dieta (alimentos ricos en histamina o liberadores de histamina) o una capacidad reducida del organismo para degradarla.

