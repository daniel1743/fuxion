### El laboratorio más exigente del cuerpo está bajo amenaza

El hígado es, en términos bioquímicos, el órgano más versátil del cuerpo humano. En este único órgano —que pesa entre 1.3 y 1.7 kilogramos— ocurren simultáneamente más de 500 funciones metabólicas documentadas: sintetiza proteínas plasmáticas, gestiona el metabolismo de carbohidratos, lípidos y proteínas, desintoxica el torrente sanguíneo de sustancias exógenas, regula los niveles de glucosa entre comidas, produce sales biliares para la digestión de grasas, almacena vitaminas liposolubles y glucógeno, y actúa como nodo central entre el tracto digestivo y el resto del organismo.

