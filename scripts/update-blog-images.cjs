const fs = require('fs');
const path = require('path');

// Mapping: article title → image file
const IMAGE_MAP = {
  'Disbiosis Intestinal': 'Disbiosis',
  'Permeabilidad Intestinal (Leaky Gut)': 'factores-modulares',
  'Síndrome del Intestino Irritable (SII)': 'sindrome-intestino-irritable',
  'SIBO (Sobrecrecimiento Bacteriano)': 'sibo',
  'Eje Intestino-Cerebro': 'eje-intestino-cerebro',
  'Hígado Graso No Alcohólico (HGNA)': 'higado-graso-hgna',
  'Reflujo Gastroesofágico (ERGE)': 'reflujo-gastroesofagico-erge',
  'Celiaquía vs Sensibilidad al Gluten No Celíaca': 'celiaquia-vs-sensibilidad-gluten',
  'Digestión enzimática exocrina': 'digestion-enzimatica-exocrina',
  'Fibra soluble vs insoluble en la motilidad': 'fibra-soluble-vs-insoluble',
  'Ácidos grasos de cadena corta (Butirato)': 'acidos-grasos-cadena-corta-butirato',
  'Estreñimiento funcional crónico': 'estrenimiento-cronico',
  'Metabolismo de los ácidos biliares': 'metabolismo-acidos-biliares',
  'Infección por Helicobacter pylori': 'helicobacter-pylori',
  'Eje intestino-hígado': 'eje-intestino-higado',
  'Intolerancia a la lactosa (Genética vs Adquirida)': 'intolerancia-a-la-lactosa',
  'Alergias alimentarias y respuesta IgE': 'alergias-alimentarias-ige',
  'Histaminosis entérica': 'histaminosis-enterica',
  'Función del moco gástrico': 'funcion-moco-gastrico',
  'Tránsito intestinal acelerado': 'transito-intestinal-acelerado-principal',
};

const SRC_DIR = path.join(__dirname, '..', 'public', 'images', 'articles-webp');

console.log('Generating SQL to update blog_posts.image_url...\n');

const lines = [];
for (const [title, imgBase] of Object.entries(IMAGE_MAP)) {
  const imgFile = `${imgBase}.webp`;
  const imgPath = `/images/articles-webp/${imgFile}`;

  // Slugify
  const slug = title
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

  lines.push(`UPDATE public.blog_posts SET image_url = '${imgPath}' WHERE slug = '${slug}';`);
}

const sql = `-- Update blog_posts.image_url with specific article images
-- Generated by scripts/update-blog-images.cjs

${lines.join('\n')}
`;

console.log(sql);

// Save to file
fs.writeFileSync(
  path.join(__dirname, '..', 'supabase', 'migrations', 'update_article_images.sql'),
  sql
);

console.log('\n✓ Saved to supabase/migrations/update_article_images.sql');
